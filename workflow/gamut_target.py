"""A verification target chosen from the profile's own gamut (#133, feature B).

The master set is ONE deterministic, versioned list of colours (issue #133
§5.1), generated by Argyll's ``targen -t`` — *Incremental Far Point
Distribution*, which picks each point as far as possible from everything
already picked, so **every prefix is itself a well-spread set** (§5.2's
nesting, by construction; verified byte-compared in the planning session).
The bundled set is marked **PROVISIONAL** (§5.4 / the plan's one irreversible
decision): it may be re-cut freely until somebody outside this project relies
on a report that names it, and only then is it frozen under a version number.

For a given profile this module *selects*: every master colour is pushed
backward through the profile (its B2A — "which ink amounts produce this
colour?") and forward again (its A2B), and the round-trip ΔE76 says whether
the profile can actually reach it. Two numbers fall out, answering two
different questions (§5.1):

* **coverage** — how many of the master set this profile can print at all;
* the **chart** — reachable colours in master order, with one adjustment for
  small charts: the master list opens with a 38-entry neutral block (4 white,
  4 black, a 30-step grey wedge — the ``-e4 -B4 -g32`` of its recipe), and
  taking it whole meant a ~100-colour chart was more than a third neutral
  (Sebastian, on his ColorMunki plain-paper chart, 2026-08-12). The neutral
  block now has a **budget of about one patch in eight** (floor 6, and never
  more than half the chart): one white, one black, and grey steps taken in a
  fixed ends-first bisection order — so every prefix of the wedge is evenly
  spaced AND a subset of every longer one. The master's duplicate white/black
  patches are never budget picks (the unconditional corners already anchor
  both ends); unused budget flows to the body. The remaining slots go to the
  first reachable chromatic colours in master order, unchanged. From about
  260 colours up the budget covers white, black and every grey step.
  Everything stays deterministic (same profile + same count = same chart),
  and any smaller chart's colours are a subset of any larger chart's for the
  same profile.

The eight cube corners are appended **unconditionally, outside the filter**
(§9a): they measure how far the ink and paper reach, which is a property the
profile has no say in, so the gamut filter must never remove them. They are
excluded from the accuracy statistics and reported in their own section.

The chart's ``.ti2`` ends up holding **final device values** — the profile is
applied at *build* time — so the sheet must print **raw**; the stored
colorimetric reference beside the chart is both the report's yardstick and the
marker the Print tab already reads to force Raw (feature A, §3.1a).

Process model: ``subprocess.run`` through :mod:`workflow.xicclu_runner`'s
injectable runners — never the ArgyllRunner singleton, always with a timeout.
"""

#: (profile path, profile digest, intent letter, bin dir, colour count, colour
#: digest) → (device, back). Bounded, because each entry holds two rows per
#: colour asked about.
_ROUND_TRIP_CACHE: "dict[tuple, tuple[list, list]]" = {}
_ROUND_TRIP_CACHE_MAX = 3


def clear_round_trip_cache() -> None:
    """Forget every remembered round trip. For tests, and for anything that
    wants the profiles re-read from disk."""
    _ROUND_TRIP_CACHE.clear()
    _DENSITY_CACHE.clear()


#: One question to xicclu at a time for the REAL runner, so a reach asked in
#: the background (:func:`gamut_coverage_async`, the first click on FROM
#: PROFILE GAMUT) and a Generate pressed while it runs do not both ask the
#: same profile the same thing: the second waits and then reads the memo.
_CACHE_LOCK = threading.RLock()


def _round_trip(labs, profile, bin_dir, letter, runner):
    """:func:`_round_trip_unlocked`, one real question at a time."""
    if runner is subprocess.run:
        with _CACHE_LOCK:
            return _round_trip_unlocked(labs, profile, bin_dir, letter, runner)
    return _round_trip_unlocked(labs, profile, bin_dir, letter, runner)


def _round_trip_unlocked(
    labs: "list[tuple[float, float, float]]",
    profile: Path,
    bin_dir: "str | Path",
    letter: str,
    runner: "Callable[..., subprocess.CompletedProcess]",
) -> "tuple[list, list]":
    """Lab → device → Lab′ through *profile*, the one place that asks.

    **THE MARGIN IS NOT PART OF THE QUESTION.** It is a threshold applied to
    the answer, and so is the patch count, so re-asking xicclu when only one
    of those changed spends seconds re-deriving numbers that cannot have
    moved. Both entry points share this function and its memo, so flicking
    Margin after the reach is known costs nothing.

    Only a REAL ``subprocess.run`` is remembered. An injected runner is a
    test's stand-in for the process and its answers are the test's business,
    so those callers always re-run.
    """
    from workflow.xicclu_runner import XiccluError, backward_device, forward_lab

    key = None
    if runner is subprocess.run:
        try:
            # THE PROFILE'S CONTENTS, not its name and timestamp. `shutil.copy2`
            # PRESERVES the modification time, and ChromIQ really does copy an
            # ICC onto a run's own profile path that way (`ui/ti2_loader.py`
            # importing a measurement with its profile beside it), so path +
            # size + mtime can describe two different profiles. Reading it
            # costs about 2 ms against the second this saves, and it makes a
            # stale answer impossible rather than unlikely.
            h = hashlib.blake2b(profile.read_bytes(), digest_size=16)
            # THE COLOURS THEMSELVES, digested too, because `flags_in_gamut` is
            # handed an arbitrary list by the measurement report: a key that
            # said only how MANY there were would serve one set of colours the
            # answer computed for a different set of the same length.
            c = hashlib.blake2b(digest_size=16)
            for lab in labs:
                c.update(struct.pack("<3d", *lab))
            # The PATH joins both digests. Two identical profiles in two places
            # then get an entry each, which is a little wasteful and never
            # wrong; keying on the contents alone made every caller holding the
            # same small stand-in profile share one answer, which is how this
            # broke `test_gamut_target.py` when it was first written.
            key = (str(profile.resolve()), h.hexdigest(), letter,
                   str(bin_dir), len(labs), c.hexdigest())
        except (OSError, struct.error, TypeError):
            key = None
    if key is not None and key in _ROUND_TRIP_CACHE:
        return _ROUND_TRIP_CACHE[key]

    try:
        # RGB output profiles have no K channel — no -k rule.
        # THE NUMERIC INVERSE, because this device value is going on paper.
        # `-fb` reads the profile's baked B2A table, which is a fast
        # approximation of an inverse; over the eleven bundled sets it lands
        # 0.366 dE00 from the aim on average against 0.052 for `-fif`, and 659
        # of 792 patches inside 0.5 against 770. It cost 0.17 s for 1,617.
        device = backward_device(labs, profile, bin_dir, intent=letter,
                                 k_rule=None, numeric_inverse=True,
                                 runner=runner)
        back = forward_lab(device, profile, bin_dir, intent=letter,
                           runner=runner)
    except XiccluError as exc:
        raise GamutTargetError(str(exc)) from exc

    if key is not None:
        while len(_ROUND_TRIP_CACHE) >= _ROUND_TRIP_CACHE_MAX:
            _ROUND_TRIP_CACHE.pop(next(iter(_ROUND_TRIP_CACHE)))
        _ROUND_TRIP_CACHE[key] = (device, back)
    return device, back


def _corner_seed_labs(profile: Path, bin_dir: "str | Path", letter: str,
                      runner: "Callable[..., subprocess.CompletedProcess]"
                      ) -> "list[tuple[float, float, float]]":
    """Where the eight corners land on paper, as the profile says, for the
    spreading pass to keep its distance from. Only a spacing hint, never
    written to any file, so when the profile cannot be asked the ideal
    corners stand in (and the log says so)."""
    from workflow.xicclu_runner import forward_lab
    try:
        labs = forward_lab(list(CORNER_DEVICES), profile, bin_dir,
                           intent=letter, runner=runner)
        if len(labs) == len(CORNER_DEVICES):
            return [tuple(float(v) for v in lab) for lab in labs]
    except Exception:                                  # noqa: BLE001
        log.info("gamut selection: corners not read through the profile; "
                 "spacing from the ideal corners", exc_info=True)
    return _corner_ideal_labs()


def _round_trip_near(labs, profile: Path, bin_dir: "str | Path", letter: str,
                     runner: "Callable[..., subprocess.CompletedProcess]",
                     density) -> "tuple[list, list]":
    """:func:`_round_trip` for the colours that CAN be reachable; ``None``
    for the device and the answer of every other one.

    Most of the wide cube is far outside any one printer's gamut, and the
    numeric inverse costs about half a millisecond a colour, so asking about
    all 16,608 tripled the time a chart took on Knut's profile (8.1 s
    against 2.7 s). A colour the profile prints lands inside one cell of the
    25-step device grid :func:`_gamut_density` read, so within that cell's
    largest corner-to-corner distance of one of its corners; one that passes
    the round trip is within the margin's threshold of where it lands. So a
    colour further than both together, plus 1.0 dE76 to spare, from every
    point of the grid cannot pass, and is not asked about. The WIDER margin's
    threshold is used whichever is chosen, so the question, and the memo of
    its answer, is the same for both: flicking Margin still costs nothing. Measured over three
    profiles, both intents and both margins: the same charts, to the patch.
    With no *density* every colour is asked, as before."""
    if density is None:
        return _round_trip(labs, profile, bin_dir, letter, runner)
    import numpy as np
    grid, cell = density[2], density[3]
    _idx, dist = _nearest(np.asarray(labs, dtype=float), grid)
    reach = cell + max(MARGIN_THRESHOLD_DE76.values()) + 1.0
    near = np.flatnonzero(dist <= reach)
    device: list = [None] * len(labs)
    back: list = [None] * len(labs)
    if len(near):
        d_near, b_near = _round_trip([labs[i] for i in near], profile,
                                     bin_dir, letter, runner)
        for j, i in enumerate(near):
            device[int(i)] = d_near[j]
            back[int(i)] = b_near[j]
    return device, back


#: (profile path, profile digest, intent letter, bin dir) -> (centres,
#: volumes, grid, cell).
_DENSITY_CACHE: "dict[tuple, tuple]" = {}
_DENSITY_GRID = 25


def _gamut_density(profile, bin_dir, letter, runner):
    """:func:`_gamut_density_unlocked`, one real question at a time."""
    if runner is subprocess.run:
        with _CACHE_LOCK:
            return _gamut_density_unlocked(profile, bin_dir, letter, runner)
    return _gamut_density_unlocked(profile, bin_dir, letter, runner)


def _gamut_density_unlocked(profile: Path, bin_dir: "str | Path", letter: str,
                            runner: "Callable[..., subprocess.CompletedProcess]"):
    """The profile's gamut VOLUME as weighted samples: ``(centres, volumes,
    grid, cell)``, *grid* the grid's own Lab points and *cell* the largest
    distance between two corners of one grid cell (see :func:`_round_trip_near`).

    A 25 x 25 x 25 device grid is read forward through the profile (one
    xicclu call, in the chart's intent); each of the 13,824 grid cells is
    one sample at its Lab centre, weighted by the Lab volume it fills (six
    tetrahedra). So a region of the gamut counts by its size in colour, not
    by how many device values happen to land in it, which is what makes the
    spread follow the gamut's shape. None when the profile cannot be read
    that way (the caller then lets the reachable colours stand in)."""
    import numpy as np
    key = None
    if runner is subprocess.run:
        try:
            h = hashlib.blake2b(profile.read_bytes(), digest_size=16)
            key = (str(profile.resolve()), h.hexdigest(), letter, str(bin_dir))
        except OSError:
            key = None
    if key is not None and key in _DENSITY_CACHE:
        return _DENSITY_CACHE[key]
    from workflow.xicclu_runner import forward_lab
    n = _DENSITY_GRID
    g = np.linspace(0.0, 100.0, n)
    r, gg, b = np.meshgrid(g, g, g, indexing="ij")
    dev = np.stack([r.ravel(), gg.ravel(), b.ravel()], axis=1)
    try:
        lab = np.asarray(forward_lab([tuple(v) for v in dev], profile, bin_dir,
                                     intent=letter, runner=runner), dtype=float)
        lab = lab.reshape(n, n, n, 3)
    except Exception:                                  # noqa: BLE001
        log.info("gamut selection: the gamut volume could not be read; the "
                 "reachable colours stand in for it", exc_info=True)
        return None
    c = [lab[i:n - 1 + i, j:n - 1 + j, k:n - 1 + k].reshape(-1, 3)
         for i in (0, 1) for j in (0, 1) for k in (0, 1)]
    vol = np.zeros(len(c[0]))
    for t0, t1, t2, t3 in ((0, 1, 3, 7), (0, 1, 5, 7), (0, 2, 3, 7),
                           (0, 2, 6, 7), (0, 4, 5, 7), (0, 4, 6, 7)):
        vol += np.abs(np.einsum("ij,ij->i", c[t1] - c[t0],
                                np.cross(c[t2] - c[t0], c[t3] - c[t0]))) / 6.0
    diam = np.zeros(len(c[0]))
    for a in range(8):
        for b2 in range(a + 1, 8):
            diam = np.maximum(diam, np.linalg.norm(c[a] - c[b2], axis=1))
    out = (np.mean(c, axis=0), vol, lab.reshape(-1, 3), float(diam.max()))
    if not np.all(np.isfinite(out[0])) or vol.sum() <= 0:
        return None
    if key is not None:
        while len(_DENSITY_CACHE) >= _ROUND_TRIP_CACHE_MAX:
            _DENSITY_CACHE.pop(next(iter(_DENSITY_CACHE)))
        _DENSITY_CACHE[key] = out
    return out


#: A reachable neutral candidate this close (dE76) to the black or the white
#: corner as the profile prints them would only repeat that corner, which is
#: on every chart anyway, so it is never a grey step.
GREY_CORNER_REPEAT_DE76 = 1.0


def _grey_steps(neutral: "list[int]", back, corners_as_printed,
                count: int) -> "list[int]":
    """The grey steps along the neutral axis (k82: "plus the grey steps
    following the neutral line").

    **EVERY GREY STEP OF THE CANDIDATE LIST'S GREY WEDGE THE PROFILE CAN
    REACH, up to :func:`_neutral_budget`** (about one patch in eight, as
    4.3.4 placed them; Basti, 2026-10-23). When the wedge holds more reachable
    steps than the budget, the steps are chosen evenly spaced in L* from the
    darkest to the lightest neutral the profile REACHES, both ends included,
    each the reachable neutral nearest its place.

    Why not the black and the white corner as the ends, as 4.3.5 to 4.3.9
    did: on a printer whose black is not neutral (jctay's Canon Selphy
    CP1500, forum 149811) no neutral can be printed anywhere near the black
    corner, so steps spaced between the corners bunched in the light half
    and the chart had eight steps the report's grey rows could not use
    (`measurement_report.pick_even_grey_steps`). And why every reachable
    step rather than as many as fit at the chart's spacing: those eight were
    too few to be roughly evenly spaced on such a profile; 4.3.4 placed the
    whole reachable wedge and its grey rows answered.

    A neutral within :data:`GREY_CORNER_REPEAT_DE76` of a corner as printed
    would only repeat that corner and is never a step; neither is a second
    candidate within `measurement_report.GREY_LEVEL_TOL` (0.5) L* of a step
    already taken, which the report's grey rows count as the same step (the
    list holds the sRGB wedge and the ProPhoto cube's own greys, a few of them
    0.1 to 0.4 L* apart)."""
    if not neutral or count < 1:
        return []
    import numpy as np
    from workflow.measurement_report import GREY_LEVEL_TOL
    ends = [tuple(map(float, corners_as_printed[0])),
            tuple(map(float, corners_as_printed[1]))]
    cand: "list[int]" = []
    for i in sorted(neutral, key=lambda k: (float(back[k][0]), k)):
        lab = tuple(map(float, back[i]))
        if any(math.dist(lab, c) < GREY_CORNER_REPEAT_DE76 for c in ends):
            continue
        if cand and lab[0] - float(back[cand[-1]][0]) < GREY_LEVEL_TOL:
            continue
        cand.append(i)
    g = min(_neutral_budget(count), len(cand))
    if g <= 0:
        return []
    if g >= len(cand):
        return cand
    ls = np.asarray([back[i][0] for i in cand], dtype=float)
    out: "list[int]" = []
    taken: "set[int]" = set()
    for t in np.linspace(ls[0], ls[-1], g):
        for j in np.argsort(np.abs(ls - t), kind="stable"):
            if int(j) not in taken:
                taken.add(int(j))
                out.append(cand[int(j)])
                break
    return out


def _nearest(a, b, chunk: int = 2048):
    """For each row of *a*: (index of the nearest row of *b*, its distance)."""
    import numpy as np
    idx = np.empty(len(a), dtype=int)
    dist = np.empty(len(a))
    bb = (b * b).sum(1)
    for s0 in range(0, len(a), chunk):
        x = a[s0:s0 + chunk]
        d2 = (x * x).sum(1)[:, None] - 2.0 * (x @ b.T) + bb[None, :]
        j = d2.argmin(1)
        idx[s0:s0 + chunk] = j
        dist[s0:s0 + chunk] = np.sqrt(np.maximum(d2[np.arange(len(x)), j], 0.0))
    return idx, dist


def _even_spread(cands, fixed, n: int, samples, weights) -> "list[int]":
    """*n* of the candidate colours *cands* (Lab rows), spread EVENLY over the
    gamut volume the weighted *samples* describe, around the *fixed* patches
    (corners and grey steps) the chart has anyway. Returns indices into
    *cands*; deterministic.

    Three steps (k82; the numbers that chose them are in the 4.3.5 report):

    1. **Farthest point** from the fixed patches: a well-spread start.
    2. **Lloyd's relaxation** (a centroidal Voronoi tessellation) over the
       volume samples: each patch moves to the centre of the part of the
       gamut it is the nearest patch to, until they stop moving. This is what
       makes the spread even through the VOLUME, so the spacing follows the
       patch count and the gamut's shape, and the outer shell is not
       over-sampled as a farthest-point set over-samples it. Each patch is
       then put on the nearest free candidate colour (nearest pairs first).
    3. **Maximin exchange**: while the patch in the tightest spot can be
       moved to a free candidate further from every other patch than it is
       now, it is moved there. This removes the pairs the snapping in step 2
       leaves too close and fills the last holes, so no two patches are
       closer than they need to be.
    """
    import numpy as np
    m = len(cands)
    if n <= 0 or m == 0:
        return []
    if n >= m:
        return list(range(m))
    cands = np.asarray(cands, dtype=float)
    fixed = np.asarray(fixed, dtype=float).reshape(-1, 3)
    samples = np.asarray(samples, dtype=float)
    weights = np.asarray(weights, dtype=float)
    f = len(fixed)

    # 1. farthest point
    dist = np.full(m, np.inf)
    if f:
        dist = _nearest(cands, fixed)[1]
    picks: "list[int]" = []
    for _ in range(n):
        j = int(np.argmax(dist))
        picks.append(j)
        dist = np.minimum(dist, np.linalg.norm(cands - cands[j], axis=1))
        dist[j] = -1.0

    # 2. Lloyd over the gamut volume, then the nearest free candidates
    sites = cands[picks].copy()
    for _ in range(40):
        pts = np.vstack([fixed, sites]) if f else sites
        owner = _nearest(samples, pts)[0]
        w = np.bincount(owner, weights=weights, minlength=len(pts))[f:]
        cen = np.stack([np.bincount(owner, weights=weights * samples[:, k],
                                    minlength=len(pts))[f:] for k in range(3)],
                       axis=1)
        new = sites.copy()
        has = w > 0
        new[has] = cen[has] / w[has, None]
        shift = float(np.max(np.linalg.norm(new - sites, axis=1)))
        sites = new
        if shift < 0.05:
            break
    k_near = min(48, m)
    pairs = []
    for si in range(n):
        d = np.linalg.norm(cands - sites[si], axis=1)
        for c in np.argsort(d, kind="stable")[:k_near]:
            pairs.append((float(d[c]), si, int(c)))
    pairs.sort()
    got: "dict[int, int]" = {}
    used = np.zeros(m, dtype=bool)
    for _d, si, c in pairs:
        if si in got or used[c]:
            continue
        got[si] = c
        used[c] = True
    for si in range(n):
        if si not in got:
            d = np.linalg.norm(cands - sites[si], axis=1)
            d[used] = np.inf
            c = int(np.argmin(d))
            got[si] = c
            used[c] = True
    body = [got[si] for si in range(n)]

    # 3. maximin exchange
    pts = np.vstack([fixed, cands[body]])
    total = len(pts)
    dmat = np.linalg.norm(pts[:, None, :] - pts[None, :, :], axis=2)
    np.fill_diagonal(dmat, np.inf)
    c_near, c_dist = _nearest(cands, pts)
    for _step in range(4 * n):
        nn = dmat[f:].min(axis=1)
        second = np.partition(dmat[f:], 1, axis=1)[:, 1] if total > 2 else nn
        moved = False
        for i in map(int, np.lexsort((second, nn))[:8]):
            k = f + i
            d = c_dist.copy()
            hit = np.flatnonzero(c_near == k)
            others = np.delete(np.arange(total), k)
            if len(hit):
                a_idx, a_dist = _nearest(cands[hit], pts[others])
                d[hit] = a_dist
            d[used] = -1.0
            c = int(np.argmax(d))
            if d[c] <= nn[i] + 1e-9:
                continue
            used[body[i]] = False
            used[c] = True
            body[i] = c
            pts[k] = cands[c]
            row = np.linalg.norm(pts - pts[k], axis=1)
            row[k] = np.inf
            dmat[k, :] = row
            dmat[:, k] = row
            if len(hit):
                c_near[hit] = others[a_idx]
                c_dist[hit] = a_dist
            dn = np.linalg.norm(cands - pts[k], axis=1)
            closer = dn < c_dist
            c_near[closer] = k
            c_dist[closer] = dn[closer]
            moved = True
            break
        if not moved:
            break
    return body



#: How the chart's body is spread over the gamut. ``even`` is the shipped
#: k82 selection (:func:`_even_spread`, from the fixed candidate list).
#: ``grid`` is Knut's stepwise grid (#182 6113365581), EXPERIMENTAL and off:
#: a regular lattice in L*a*b* whose spacing is doubled, then halved in
#: alternating directions until the count inside the gamut is the goal, the
#: rest at the centres between lattice points (:func:`_stepwise_grid`). Its
#: colours are lattice points, not candidates of the k83 list, so switching it
#: on contradicts k83 and needs Knut's and Sebastian's approval (spec 9a, E5).
SPREAD_EVEN = "even"
SPREAD_GRID = "grid"
SPREADS = (SPREAD_EVEN, SPREAD_GRID)


class _GamutSolid:
    """Everything *a profile can print*, as the solid the device cube maps
    to: the 25-step device grid of :func:`_gamut_density` read through the
    profile, each grid cell cut into six tetrahedra. A colour is inside when
    it lies in the image of one of them. On a printer whose response folds
    (a laser's own driver: Knut's CLJ5550 prints a more colourful green at
    G=53 than at G=100) the images overlap, and "inside any" is still the
    right answer: some ink amount prints it.

    Tetrahedra are bucketed by a voxel grid so a lookup only tests the few
    whose bounding box holds the point; numpy only."""

    _TETS = ((0, 1, 3, 7), (0, 1, 5, 7), (0, 2, 3, 7),
             (0, 2, 6, 7), (0, 4, 5, 7), (0, 4, 6, 7))

    def __init__(self, grid_lab, n: int = None, voxel: float = 4.0):
        import numpy as np
        g = np.asarray(grid_lab, dtype=float)
        n = n or round(len(g) ** (1.0 / 3.0))
        g = g.reshape(n, n, n, 3)
        corners = [g[i:n - 1 + i, j:n - 1 + j, k:n - 1 + k].reshape(-1, 3)
                   for i in (0, 1) for j in (0, 1) for k in (0, 1)]
        v0, e1, e2, e3 = [], [], [], []
        for a, b, c, d in self._TETS:
            v0.append(corners[a])
            e1.append(corners[b] - corners[a])
            e2.append(corners[c] - corners[a])
            e3.append(corners[d] - corners[a])
        self.v0 = np.vstack(v0)
        m = np.stack([np.vstack(e1), np.vstack(e2), np.vstack(e3)], axis=2)
        det = np.linalg.det(m)
        ok = np.abs(det) > 1e-9
        self.v0, m = self.v0[ok], m[ok]
        self.inv = np.linalg.inv(m)
        pts = np.stack([self.v0, self.v0 + m[:, :, 0], self.v0 + m[:, :, 1],
                        self.v0 + m[:, :, 2]], axis=1)
        self.lo_box, self.hi_box = pts.min(axis=1), pts.max(axis=1)
        self.lo = self.lo_box.min(axis=0)
        self.hi = self.hi_box.max(axis=0)
        self.voxel = float(voxel)
        a = np.floor((self.lo_box - self.lo) / self.voxel).astype(int)
        b = np.floor((self.hi_box - self.lo) / self.voxel).astype(int)
        self.dims = np.floor((self.hi - self.lo) / self.voxel).astype(int) + 1
        buckets: "dict[int, list[int]]" = {}
        for t in range(len(a)):
            for x in range(a[t, 0], b[t, 0] + 1):
                for y in range(a[t, 1], b[t, 1] + 1):
                    for z in range(a[t, 2], b[t, 2] + 1):
                        buckets.setdefault(
                            (x * self.dims[1] + y) * self.dims[2] + z,
                            []).append(t)
        self.buckets = {k: np.asarray(v) for k, v in buckets.items()}

    def inside(self, points) -> "list[bool]":
        import numpy as np
        p = np.asarray(points, dtype=float).reshape(-1, 3)
        out = np.zeros(len(p), dtype=bool)
        vox = np.floor((p - self.lo) / self.voxel).astype(int)
        inbox = np.all((vox >= 0) & (vox < self.dims), axis=1)
        keys = (vox[:, 0] * self.dims[1] + vox[:, 1]) * self.dims[2] + vox[:, 2]
        for i in np.flatnonzero(inbox):
            tets = self.buckets.get(int(keys[i]))
            if tets is None:
                continue
            q = p[i]
            box = np.all((self.lo_box[tets] <= q) & (q <= self.hi_box[tets]),
                         axis=1)
            tets = tets[box]
            if not len(tets):
                continue
            lam = np.einsum("tij,tj->ti", self.inv[tets], q - self.v0[tets])
            if np.any(np.all(lam >= -1e-9, axis=1)
                      & (lam.sum(axis=1) <= 1.0 + 1e-9)):
                out[i] = True
        return out


def _lattice(spacing: float, lo, hi, anchor) -> "object":
    """Every point of the cubic lattice with *spacing* through *anchor*
    inside the box *lo*..*hi* (L*, a*, b*)."""
    import numpy as np
    axes = []
    for k in range(3):
        first = math.floor((lo[k] - anchor[k]) / spacing)
        last = math.ceil((hi[k] - anchor[k]) / spacing)
        axes.append(np.arange(first, last + 1) * spacing + anchor[k])
    return np.stack(np.meshgrid(*axes, indexing="ij"), -1).reshape(-1, 3)


def _stepwise_grid(goal: int, solid: "_GamutSolid", fixed, start: float,
                   *, max_steps: int = 40):
    """Knut's stepwise grid (#182 6113365581), in L*a*b*.

    A cubic lattice of spacing *s* is laid over the gamut; its points inside
    the gamut (and not within half a spacing of a *fixed* patch, the corners
    and grey steps the chart has anyway) are counted. Starting a little
    denser than the goal, the spacing is doubled until fewer than *goal*
    points are inside, then changed in the other direction by half the
    previous step each time the goal is passed, until the count is the goal
    or the step is negligible; the largest count at or below the goal is
    kept. Returns ``(points, centres, spacing, history)``: the lattice points
    kept, the inside centres of the lattice's cells (the places "exactly in
    between" for the remainder), the spacing, and ``[(spacing, count)]``."""
    import numpy as np
    fixed = np.asarray(fixed, dtype=float).reshape(-1, 3)
    lo, hi = solid.lo, solid.hi
    # The lattice is offset half a step off the neutral axis, so its
    # columns never stand on the grey steps.
    def count(s):
        anchor = (50.0, s / 2.0, s / 2.0)
        lat = _lattice(s, lo, hi, anchor)
        lat = lat[solid.inside(lat)]
        if len(fixed) and len(lat):
            lat = lat[_nearest(lat, fixed)[1] >= 0.5 * s]
        return lat

    history = []

    def ask(s):
        pts = count(s)
        history.append((s, len(pts)))
        return pts

    s = float(start)
    pts = ask(s)
    # Knut starts "a little denser than the goal"; a start that is not is
    # made so by halving the spacing.
    while len(pts) < goal and len(history) < max_steps:
        s /= 2.0
        pts = ask(s)
    # Double the spacing until the goal is passed...
    prev = s
    while len(pts) > goal and len(history) < max_steps:
        prev, s = s, 2.0 * s
        pts = ask(s)
    # ...then turn, half the last move each time the goal is passed again.
    best = (s, pts) if len(pts) <= goal else None
    step = (s - prev) / 2.0
    direction = -1
    while len(pts) != goal and len(history) < max_steps and step > 1e-3 * s:
        want = -1 if len(pts) < goal else +1
        if want != direction:
            direction = want
            step /= 2.0
        s = s + direction * step
        pts = ask(s)
        if len(pts) <= goal and (best is None or len(pts) > len(best[1])):
            best = (s, pts)
    if best is None:
        best = (s, pts[:goal])
    s, pts = best
    centres = _lattice(s, lo, hi, (50.0 + s / 2.0, s, s))
    centres = centres[solid.inside(centres)]
    if len(fixed) and len(centres):
        centres = centres[_nearest(centres, fixed)[1] >= 0.5 * s]
    return pts, centres, s, history


def _grid_selection(profile: Path, count: int, threshold: float, letter: str,
                    bin_dir, runner, density, corners_as_printed, greys_lab
                    ) -> "tuple[list, list, list]":
    """The body of a chart by :func:`_stepwise_grid`: ``(labs, devices,
    history)`` for ``count`` colours. Every colour kept passed the same
    round trip and printable test as a candidate of the list."""
    import numpy as np
    solid = _GamutSolid(density[2])
    fixed = np.asarray(list(corners_as_printed) + list(greys_lab),
                       dtype=float).reshape(-1, 3)
    volume = float(density[1].sum())
    start = 0.8 * (volume / max(1, count)) ** (1.0 / 3.0)
    pts, centres, s, history = _stepwise_grid(count, solid, fixed, start)
    ask = [tuple(map(float, x)) for x in np.vstack([pts, centres])] \
        if len(centres) else [tuple(map(float, x)) for x in pts]
    device, back = _round_trip(ask, profile, bin_dir, letter, runner)
    ok = [math.dist(a, b) <= threshold and device_is_printable(d)
          for a, b, d in zip(ask, back, device)]
    lat_ok = [i for i in range(len(pts)) if ok[i]]
    labs = [ask[i] for i in lat_ok][:count]
    devs = [device[i] for i in lat_ok][:count]
    # The remainder: at the centres between lattice points, each the one
    # farthest from every patch so far (Knut: "exactly in-between existing
    # patches"), so none lands on another.
    cand = [len(pts) + j for j in range(len(centres)) if ok[len(pts) + j]]
    if len(labs) < count and cand:
        have = np.vstack([fixed, np.asarray(labs).reshape(-1, 3)])
        c = np.asarray([ask[i] for i in cand], dtype=float)
        dist = _nearest(c, have)[1]
        while len(labs) < count and np.max(dist) >= 0:
            j = int(np.argmax(dist))
            labs.append(ask[cand[j]])
            devs.append(device[cand[j]])
            dist = np.minimum(dist, np.linalg.norm(c - c[j], axis=1))
            dist[j] = -1.0
    return labs, devs, history


def _fill_strip_rungs(picks: "list[int]", cands, fixed, cand_devices
                      ) -> "list[int]":
    """*picks* with a few patches exchanged so the chart can declare its
    control strip (#182, ``workflow.control_strip``).

    The strip is a ladder of device aims (paper, solids, tints of each ink
    and overprint, greys), and a rung is filled by a patch within
    ``SLOT_TOL`` of its aim. The report's three control-strip rows need 8
    rungs and the 95th-percentile row 20. An even spread chooses its colours
    in Lab and knows nothing of device tints, so on small charts it can leave
    a rung empty that the chart filled before (measured over the built-in
    presets' certificates: four presets fell below 20 rungs).

    So for each empty rung, in ladder order, the candidate near its aim that
    disturbs the spread least is exchanged for the nearest chosen patch, but
    only when it stays as far from every other patch as the closest pair of
    the spread already is: the even spacing is kept, a rung is gained where
    the gamut has a colour there anyway. A patch that fills a rung is never
    the one given up."""
    import numpy as np
    if not picks:
        return picks
    from workflow.control_strip import SLOT_TOL, SLOTS
    devs = np.asarray(cand_devices, dtype=float).reshape(-1, 3)
    picks = list(picks)
    f = len(fixed)
    pts = np.vstack([fixed, cands[picks]]) if f else cands[picks].copy()
    d = np.linalg.norm(pts[:, None] - pts[None], axis=2)
    np.fill_diagonal(d, np.inf)
    floor = float(d[f:].min()) if len(picks) > 1 else 0.0
    in_use = set(picks)
    holds: "set[int]" = set()          # picks (by position) that fill a rung
    for slot in SLOTS:
        aim = np.asarray(slot.device, dtype=float)
        if np.all((aim == 0.0) | (aim == 100.0)):
            continue                   # paper and solids: the corners fill them
        off = np.abs(devs - aim).max(axis=1)
        mine = [k for k, j in enumerate(picks)
                if k not in holds and off[j] <= SLOT_TOL]
        if mine:
            holds.add(min(mine, key=lambda k: (off[picks[k]], k)))
            continue
        best = None
        for c in np.flatnonzero(off <= SLOT_TOL):
            c = int(c)
            if c in in_use:
                continue
            gap = np.linalg.norm(pts - cands[c], axis=1)
            order = [int(k) for k in np.argsort(gap[f:], kind="stable")
                     if int(k) not in holds]
            if not order:
                continue
            k = order[0]
            rest = np.delete(gap, f + k)
            if rest.min() + 1e-9 < floor:
                continue
            key = (float(gap[f + k]), c)
            if best is None or key < best[0]:
                best = (key, c, k)
        if best is None:
            continue
        _key, c, k = best
        in_use.discard(picks[k])
        in_use.add(c)
        picks[k] = c
        pts[f + k] = cands[c]
        holds.add(k)
    return picks


def gamut_coverage(profile: Path, margin: str, intent: str, *,
                   bin_dir: "str | Path",
                   master_path: "Path | None" = None,
                   runner: "Callable[..., subprocess.CompletedProcess]" = subprocess.run,
                   ) -> "tuple[int, int]":
    """``(reachable, total)``: how many of the candidate colours *profile*
    can print with *margin*, and how many there are. The same round trip
    and the same tests as :func:`select_gamut_targets`, without choosing a
    chart (the Create Chart count line asks this on every change)."""
    profile = Path(profile)
    if not profile.is_file():
        raise GamutTargetError(f"the profile file is missing: {profile}")
    threshold = MARGIN_THRESHOLD_DE76.get(margin)
    if threshold is None:
        raise GamutTargetError(f"unknown margin {margin!r}")
    labs = load_master_labs(master_path)
    letter = intent_letter(intent)
    density = _gamut_density(profile, bin_dir, letter, runner)
    device, back = _round_trip_near(labs, profile, bin_dir, letter, runner,
                                    density)
    n = sum(1 for i, (lab, lab2) in enumerate(zip(labs, back))
            if lab2 is not None and math.dist(lab, lab2) <= threshold
            and device_is_printable(device[i]))
    return n, len(labs)


#: The background worker for :func:`gamut_coverage_async`: ONE thread, so two
#: reaches never compete for the same profile, created on first use.
_COVERAGE_POOL = None
#: In-flight reach questions by (profile, margin, intent, bin dir, list).
_COVERAGE_JOBS: dict = {}
_JOBS_LOCK = threading.Lock()


def gamut_coverage_async(profile: Path, margin: str, intent: str, *,
                         bin_dir: "str | Path",
                         master_path: "Path | None" = None):
    """:func:`gamut_coverage` on a background thread: a
    ``concurrent.futures.Future`` whose result is ``(reachable, total)`` (or
    whose exception is the one the call raised).

    Knut, #182 6113365581: the first click on FROM PROFILE GAMUT took several
    seconds and later clicks did not. That first click asked the profile about
    every candidate colour near its gamut (measured on his CLJ5550 profile:
    4.4 s of xicclu, 0.2 s more for the gamut volume) ON THE WINDOW'S THREAD,
    to write one count line; later clicks read the tab's memo. Asked here
    instead, the window stays live, and because the answer lands in the same
    memo :func:`select_gamut_targets` reads, the Generate that follows is
    faster too. A second request for the same question while the first runs
    gets the same Future. Nothing here touches Qt."""
    from concurrent.futures import ThreadPoolExecutor
    global _COVERAGE_POOL
    key = (str(profile), margin, intent, str(bin_dir), str(master_path))
    with _JOBS_LOCK:
        job = _COVERAGE_JOBS.get(key)
        if job is not None and not job.done():
            return job
        if _COVERAGE_POOL is None:
            _COVERAGE_POOL = ThreadPoolExecutor(
                max_workers=1, thread_name_prefix="chromiq-gamut-reach")
        job = _COVERAGE_POOL.submit(gamut_coverage, Path(profile), margin,
                                    intent, bin_dir=bin_dir,
                                    master_path=master_path)
        _COVERAGE_JOBS[key] = job
    return job


def select_gamut_targets(
    profile: Path,
    count: int,
    margin: str,
    intent: str,
    *,
    bin_dir: "str | Path",
    master_path: "Path | None" = None,
    runner: "Callable[..., subprocess.CompletedProcess]" = subprocess.run,
    spread: str = SPREAD_EVEN,
) -> GamutSelection:
    """Filter the candidate list through *profile* and pick *count* reachable
    colours, plus the eight corners.

    *spread* ``grid`` (EXPERIMENTAL, off by default, see :data:`SPREAD_GRID`)
    keeps the corners and grey steps and lays the rest out by Knut's stepwise
    grid instead of choosing them from the list.

    The round trip: candidate Lab → B2A → device → A2B → Lab′. A colour the
    profile can reach comes back within interpolation error; a clipped one
    lands on the gamut surface and moves far. The margin picks the threshold.
    A colour whose ink amount falls outside the device cube is not reachable
    whatever the round trip says (:func:`device_is_printable`), so it counts
    against neither ``in_gamut_total`` nor the chart.

    The chart: grey steps (:func:`_grey_steps`) and the rest spread evenly
    over the profile's gamut volume (:func:`_even_spread`), around the eight
    corners as the profile prints them; see the module docstring. The
    result is deterministic. It holds *count* colours whenever the profile
    reaches that many.
    """
    profile = Path(profile)
    if not profile.is_file():
        raise GamutTargetError(f"the profile file is missing: {profile}")
    if count < 1:
        raise GamutTargetError("the requested patch count must be at least 1")
    threshold = MARGIN_THRESHOLD_DE76.get(margin)
    if threshold is None:
        raise GamutTargetError(f"unknown margin {margin!r}")
    letter = intent_letter(intent)

    labs = load_master_labs(master_path)
    density = _gamut_density(profile, bin_dir, letter, runner)
    device, back = _round_trip_near(labs, profile, bin_dir, letter, runner,
                                    density)

    selection = GamutSelection(
        master_version=MASTER_SET_VERSION, master_total=len(labs),
        in_gamut_total=0, requested=int(count),
        intent=intent, margin=margin,
        profile_white_lab=profile_media_white_lab(profile),
        profile_name=profile.name)

    # THE ROUND TRIP ALONE IS NOT THE QUESTION: A COLOUR IS REACHABLE ONLY IF
    # ITS INK AMOUNT EXISTS. `-fif` extrapolates outside the device cube, and
    # the forward leg extrapolates back, so a colour needing device 107.69
    # returns 0.000 ΔE00 from its aim and reads as comfortably in gamut. It is
    # not: the printer receives 100, and what it prints is up to 8.86 ΔE00
    # from the aim the chart's reference file would store beside it (measured
    # over the whole master set, 238 such colours, mean 2.34). Keeping the
    # patch and clamping it writes an aim the print provably cannot hit, and
    # the verification report then charges that error to the printer. Dropping
    # it costs nothing: another reachable colour takes the
    # slot, and the chart is the size asked for.
    passing = []
    unprintable = 0
    for i, (lab, lab2) in enumerate(zip(labs, back)):
        if lab2 is None or math.dist(lab, lab2) > threshold:
            continue
        if not device_is_printable(device[i]):
            unprintable += 1
            continue
        passing.append(i)
    selection.in_gamut_total = len(passing)
    if unprintable:
        log.info("gamut selection: %d master colours round-tripped inside the "
                 "%s margin but need ink amounts outside 0..100 and are not "
                 "reachable", unprintable, margin)

    # k82 (Knut, #182 6102031563, agreed by Sebastian 2026-10-11): the chart
    # is the eight corners, grey steps along the neutral axis, and the rest
    # spread EVENLY over the profile's whole gamut volume, the spacing
    # following the patch count. See :func:`_even_spread`.
    def _is_neutral(i: int) -> bool:
        return math.hypot(labs[i][1], labs[i][2]) < 1.0

    neutral = [i for i in passing if _is_neutral(i)]
    body = [i for i in passing if not _is_neutral(i)]
    corners_as_printed = _corner_seed_labs(profile, bin_dir, letter, runner)
    greys = _grey_steps(neutral, back, corners_as_printed, count)
    chosen: "list[int]" = list(greys)

    import numpy as np
    if spread == SPREAD_GRID and density is not None:
        labs_g, devs_g, history = _grid_selection(
            profile, count - len(chosen), threshold, letter, bin_dir, runner,
            density, corners_as_printed, [back[i] for i in greys])
        for i in sorted(chosen):
            selection.targets.append((i, labs[i], snap_to_device_cube(device[i])))
        for lab, dev in zip(labs_g, devs_g):
            selection.targets.append((-1, tuple(lab), snap_to_device_cube(dev)))
        selection.corners = list(zip(CORNER_DEVICES, _corner_ideal_labs()))
        selection.spread = SPREAD_GRID
        selection.grid_history = list(history)
        log.info("gamut selection (experimental stepwise grid): %d requested, "
                 "%d chosen (%d grey steps) in %d steps + %d corners",
                 count, selection.achieved, len(greys), len(history),
                 len(selection.corners))
        return selection
    cands = np.asarray([back[i] for i in body], dtype=float).reshape(-1, 3)
    fixed = np.asarray(list(corners_as_printed) + [back[i] for i in greys],
                       dtype=float).reshape(-1, 3)
    if density is None:
        # No volume could be read (an injected runner, a profile xicclu
        # answers oddly): the reachable colours themselves stand in for it.
        density = (cands, np.ones(len(cands)))
    picks = _even_spread(cands, fixed, count - len(chosen), density[0],
                         density[1])
    picks = _fill_strip_rungs(picks, cands, fixed,
                              [device[i] for i in body])
    chosen.extend(body[j] for j in picks)
    if len(chosen) < count:
        # A gamut so small (or a chart so large) that the body runs dry:
        # top up with the remaining reachable neutrals rather than shipping
        # a shorter chart than the reachable colours allow.
        have = set(chosen)
        rest = [i for i in passing if i not in have]
        chosen.extend(rest[:count - len(chosen)])
    for i in sorted(chosen):
        selection.targets.append((i, labs[i], snap_to_device_cube(device[i])))
    selection.corners = list(zip(CORNER_DEVICES, _corner_ideal_labs()))
    log.info("gamut selection: %d of %d master colours in gamut (%s margin), "
             "%d requested, %d chosen (%d grey steps) + %d corners",
             selection.in_gamut_total, selection.master_total, margin,
             count, selection.achieved, len(greys), len(selection.corners))
    return selection


def flags_in_gamut(
    labs: "list[tuple[float, float, float]]",
    profile: Path,
    bin_dir: "str | Path",
    *,
    margin: str = MARGIN_SAFE,
    intent: str = "absolute",
    runner: "Callable[..., subprocess.CompletedProcess]" = subprocess.run,
) -> "list[bool]":
    """One in/out-of-gamut flag per Lab colour, same round trip and the same
    thresholds as :func:`select_gamut_targets` — Lab → B2A → device → A2B →
    Lab′; a reachable colour comes back within interpolation error, a clipped
    one lands on the gamut surface and moves far. Used by the measurement
    report's split statistics (Knut, 2026-08-10).

    Shares :func:`_round_trip` with :func:`select_gamut_targets`, so the
    numeric inverse is asked for in one place and the two can never drift into
    answering the same question differently."""
    profile = Path(profile)
    if not profile.is_file():
        raise GamutTargetError(f"the profile file is missing: {profile}")
    threshold = MARGIN_THRESHOLD_DE76.get(margin)
    if threshold is None:
        raise GamutTargetError(f"unknown margin {margin!r}")
    letter = intent_letter(intent)
    _device, back = _round_trip(list(labs), profile, bin_dir, letter, runner)
    return [math.dist(lab, lab2) <= threshold
            for lab, lab2 in zip(labs, back)]



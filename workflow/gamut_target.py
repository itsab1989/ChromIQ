"""A verification target chosen from the profile's own gamut (#133, feature B).

**The candidate list** (``PROVISIONAL-r2`` since 4.3.5, k83) is one fixed,
deterministic list of colours, the same for every printer: the 5,960 colours
of the r1 set, generated by Argyll's ``targen -t`` in sRGB (white, black, a
grey wedge and a far-point spread), PLUS a whole 22 x 22 x 22 cube in
ProPhoto RGB (:func:`wide_cube_labs`, 10,648 colours), so a wide-gamut
printer's colours beyond sRGB and Adobe RGB (1998) are on the list too
(Knut, #182 6102031563: "colors that any professional printer may achieve").
The sets are marked **PROVISIONAL** (§5.4): they may be re-cut freely until
somebody outside this project relies on a report that names one.

For a given profile this module *selects*: every candidate colour is pushed
backward through the profile (its B2A — "which ink amounts produce this
colour?") and forward again (its A2B), and the round-trip ΔE76 says whether
the profile can actually reach it — **together with the ink amount itself,
which has to exist**: the numeric inverse answers outside the device cube and
the forward leg extrapolates back, so a colour needing device 107.69 round
trips perfectly and is still unprintable (:func:`device_is_printable`). Two
numbers fall out, answering two different questions (§5.1):

* **coverage** — how many of the candidates this profile can print at all;
* the **chart** (k82, Knut #182 6102031563, agreed by Sebastian 2026-10-11):
  the eight corners, **grey steps** along the neutral axis: every step of the
  grey wedge the profile can reach, never more than about one patch in eight
  (Sebastian 2026-08-12), spaced evenly from the darkest to the lightest grey
  the profile reaches when there are more (Basti 2026-10-23), and the
  rest spread **evenly over the profile's whole gamut volume**: the spacing
  follows the patch count, no two patches closer than they need to be, no
  region left empty (:func:`_even_spread`). Until 4.3.4 the body was a
  farthest-point order, so a smaller chart was a prefix of a larger one;
  that nesting is given up for the even spread, which is chosen for each
  count on its own. Everything stays deterministic: same profile, same
  settings, same count, same chart.

The eight cube corners are appended **unconditionally, outside the filter**
(§9a): they measure how far the ink and paper reach, which is a property the
profile has no say in, so the gamut filter must never remove them. They are
excluded from the accuracy statistics and reported in their own section.

The chart's ``.ti2`` ends up holding **final device values** — the profile is
applied at *build* time — so the sheet must print **raw**; the stored
colorimetric reference beside the chart is both the report's yardstick and the
marker the Print tab already reads to force Raw (feature A, §3.1a).

Process model: ``subprocess.run`` through :mod:`workflow.xicclu_runner`'s
injectable runners — never the ArgyllRunner singleton, always with a timeout.
"""

#: The published master set (PROVISIONAL — see the module docstring).
MASTER_SET_VERSION = "PROVISIONAL-r1"
MASTER_SET_ASSET = f"assets/verification/chromiq-verification-set-{MASTER_SET_VERSION}.ti1"

#: §6 — the two margin choices. "Safe" keeps targets away from the gamut
#: boundary with a tightened round-trip threshold; "full" allows everything
#: the profile can technically reach.
MARGIN_SAFE = "safe"
MARGIN_FULL = "full"
#: ΔE76 round-trip thresholds. 3.0 is the boundary the #72 perceptual bridge
#: measured as empirically clean (fully-in-gamut sets stay under it, clipped
#: sets land far above — ``xicclu_runner.to_device_via_profile``); 1.5 is the
#: tightened "comfortably inside" variant. PROVISIONAL until the first real
#: print confirms them.
MARGIN_THRESHOLD_DE76 = {MARGIN_SAFE: 1.5, MARGIN_FULL: 3.0}

#: §7 — the module's one intent choice, applied to BOTH the chart build and
#: the reading, recorded in the reference file. Absolute matches the practice
#: this feature replaces; media-relative isolates the profile from the paper
#: white. Stored under these names; xicclu letters via :func:`intent_letter`.
INTENT_ABSOLUTE = "absolute"
INTENT_RELATIVE = "relative"
_INTENT_LETTER = {INTENT_ABSOLUTE: "a", INTENT_RELATIVE: "r"}

#: The eight cube corners in the measurement report's own order
#: (``measurement_report.CUBE_CORNERS``: W K R G B C M Y), device 0..100.
CORNER_DEVICES: "tuple[tuple[float, float, float], ...]" = (
    (100.0, 100.0, 100.0), (0.0, 0.0, 0.0),
    (100.0, 0.0, 0.0), (0.0, 100.0, 0.0), (0.0, 0.0, 100.0),
    (0.0, 100.0, 100.0), (100.0, 0.0, 100.0), (100.0, 100.0, 0.0),
)


class GamutTargetError(RuntimeError):
    """Selection could not run (missing master set, unusable profile, …)."""


def intent_letter(intent: str) -> str:
    return _INTENT_LETTER.get(intent, "a")


def master_set_path() -> Path:
    return Path(resource_path(MASTER_SET_ASSET))


@dataclass
class GamutSelection:
    """The outcome of filtering the master set through one profile."""

    master_version: str
    master_total: int             #: size of the master set
    in_gamut_total: int           #: coverage — reachable master colours
    requested: int                #: what the user asked for
    intent: str                   #: "absolute" | "relative"
    margin: str                   #: "safe" | "full"
    #: The chart body, in master (nested) order: (master_index, master Lab,
    #: device 0..100). len == min(requested, in_gamut_total).
    targets: "list[tuple[int, tuple[float, float, float], tuple[float, ...]]]" = field(default_factory=list)
    #: The §9a corners: (device, ideal sRGB Lab), appended after the targets.
    corners: "list[tuple[tuple[float, ...], tuple[float, float, float]]]" = field(default_factory=list)

    @property
    def achieved(self) -> int:
        return len(self.targets)

    @property
    def total_patches(self) -> int:
        return len(self.targets) + len(self.corners)


def load_master_labs(path: "Path | None" = None) -> "list[tuple[float, float, float]]":
    """The master set as Lab (D50), in its published (nested) order.

    The set is generated with an sRGB conditioning profile, so targen's XYZ
    column is D65-referenced; it is Bradford-adapted to D50 here with exactly
    the machinery the measurement report uses for design values, so the
    targets and the report speak the same white point.
    """
    from workflow.measurement_report import (_bradford_d65_to_d50,
                                             _design_xyz_is_d65,
                                             _design_xyz_to_100)
    from workflow.ti3_analysis import parse_ti3, xyz_to_lab
    import numpy as np
    p = Path(path) if path is not None else master_set_path()
    if not p.is_file():
        raise GamutTargetError(
            f"the master colour set is missing: {p.name}")
    data = parse_ti3(p)
    xyz = _design_xyz_to_100(np.asarray(data.xyz, dtype=float))
    adapt = _design_xyz_is_d65(data.keywords)
    out = []
    for x, y, z in xyz:
        if adapt:
            x, y, z = _bradford_d65_to_d50(float(x), float(y), float(z))
        out.append(xyz_to_lab((float(x) / 100.0, float(y) / 100.0,
                               float(z) / 100.0)))
    return out


def _corner_ideal_labs() -> "list[tuple[float, float, float]]":
    """The corners' reference Lab — the ideal device corners read as sRGB,
    exactly the reading the report's design reference has always used, so the
    corner trend stays comparable across chart kinds."""
    from workflow.xicclu_runner import _srgb_to_lab_rows
    return _srgb_to_lab_rows(list(CORNER_DEVICES))


def _master_keywords(path: "Path | None" = None) -> dict:
    """The master set's own header keywords ({} when unreadable)."""
    from workflow.ti3_analysis import parse_ti3
    p = Path(path) if path is not None else master_set_path()
    try:
        return dict(parse_ti3(p).keywords or {})
    except Exception:      # noqa: BLE001 — no keywords just means no budgeting
        return {}


def _neutral_prefix_counts(keywords: dict) -> "tuple[int, int, int]":
    """``(whites, blacks, mid greys)`` at the START of the master order, read
    from the set's own header (targen stamps its recipe there). A master
    without the keywords — a test fixture, a custom set — gets ``(0, 0, 0)``
    and the selection stays the plain first-*n* prefix."""
    try:
        w = int(keywords.get("WHITE_COLOR_PATCHES", 0))
        k = int(keywords.get("BLACK_COLOR_PATCHES", 0))
        # targen counts white and black as the wedge's own endpoints.
        g = max(0, int(keywords.get("COMP_GREY_STEPS", 0)) - 2)
    except (TypeError, ValueError):
        return (0, 0, 0)
    return (max(0, w), max(0, k), g)


def _neutral_budget(count: int) -> int:
    """How many of *count* requested colours the neutral block may take:
    about one in eight, floor 6, never more than half the chart."""
    return min(max(6, round(count / 8)), count // 2)


def _spread_order(n: int) -> "list[int]":
    """``0..n-1`` in an ends-first bisection order: every prefix is an
    approximately even sample of the range, and every prefix contains all
    shorter ones — which is what keeps a small chart's grey steps a subset
    of a large chart's."""
    if n <= 0:
        return []
    if n == 1:
        return [0]
    import heapq
    order = [0, n - 1]
    seen = {0, n - 1}
    heap = [(-(n - 1), 0, n - 1)]
    while heap and len(order) < n:
        _neg, lo, hi = heapq.heappop(heap)
        if hi - lo < 2:                     # no interior point left in here
            continue
        mid = (lo + hi) // 2
        if mid not in seen:
            order.append(mid)
            seen.add(mid)
        heapq.heappush(heap, (-(mid - lo), lo, mid))
        heapq.heappush(heap, (-(hi - mid), mid, hi))
    for i in range(n):                      # safety net, ascending
        if i not in seen:
            order.append(i)
    return order


def select_gamut_targets(
    profile: Path,
    count: int,
    margin: str,
    intent: str,
    *,
    bin_dir: "str | Path",
    master_path: "Path | None" = None,
    runner: "Callable[..., subprocess.CompletedProcess]" = subprocess.run,
) -> GamutSelection:
    """Filter the master set through *profile* and pick *count* reachable
    colours, plus the eight corners.

    The round trip: master Lab → B2A → device → A2B → Lab′. A colour the
    profile can reach comes back within interpolation error; a clipped one
    lands on the gamut surface and moves far. The margin picks the threshold.

    The pick is the first *count* reachable colours in master order, EXCEPT
    that the master's opening neutral block (white, black, grey wedge — read
    from the set's own header) is capped at :func:`_neutral_budget` so a
    small chart is not swallowed by greys; see the module docstring. The
    result is deterministic, and a smaller chart's colours are a subset of a
    larger chart's for the same profile.
    """
    from workflow.xicclu_runner import XiccluError, backward_device, forward_lab
    profile = Path(profile)
    if not profile.is_file():
        raise GamutTargetError(f"the profile file is missing: {profile}")
    if count < 1:
        raise GamutTargetError("the requested patch count must be at least 1")
    threshold = MARGIN_THRESHOLD_DE76.get(margin)
    if threshold is None:
        raise GamutTargetError(f"unknown margin {margin!r}")
    letter = intent_letter(intent)

    labs = load_master_labs(master_path)
    try:
        # RGB output profiles have no K channel — no -k rule.
        device = backward_device(labs, profile, bin_dir, intent=letter,
                                 k_rule=None, runner=runner)
        back = forward_lab(device, profile, bin_dir, intent=letter,
                           runner=runner)
    except XiccluError as exc:
        raise GamutTargetError(str(exc)) from exc

    selection = GamutSelection(
        master_version=MASTER_SET_VERSION, master_total=len(labs),
        in_gamut_total=0, requested=int(count),
        intent=intent, margin=margin)

    passing = []
    for i, (lab, lab2) in enumerate(zip(labs, back)):
        if math.dist(lab, lab2) <= threshold:
            passing.append(i)
    selection.in_gamut_total = len(passing)

    # The neutral block at the head of the master order, budgeted. The
    # header says where it ends; the chroma check makes sure the entries
    # really are neutral, so a re-cut master with a different layout can
    # never make the budget pick coloured patches as "greys".
    n_w, n_k, n_g = _neutral_prefix_counts(_master_keywords(master_path))
    prefix_end = n_w + n_k + n_g

    def _is_neutral(i: int) -> bool:
        return math.hypot(labs[i][1], labs[i][2]) < 1.0

    whites = [i for i in passing if i < n_w and _is_neutral(i)]
    blacks = [i for i in passing if n_w <= i < n_w + n_k and _is_neutral(i)]
    greys = [i for i in passing
             if n_w + n_k <= i < prefix_end and _is_neutral(i)]
    neutral_all = set(whites) | set(blacks) | set(greys)

    chosen: "list[int]" = []
    if prefix_end:
        budget = _neutral_budget(count)
        if whites and len(chosen) < budget:
            chosen.append(whites[0])
        if blacks and len(chosen) < budget:
            chosen.append(blacks[0])
        # Grey steps in ends-first bisection order: evenly spaced at every
        # budget, and every smaller budget's picks are inside every larger
        # one's. The master's duplicate white/black patches are never budget
        # picks — the corners already anchor both ends, so unused budget is
        # better spent on real colours (it simply flows to the body below).
        g_room = budget - len(chosen)
        if g_room > 0 and greys:
            picks = _spread_order(len(greys))[:g_room]
            chosen.extend(greys[j] for j in sorted(picks))

    body = [i for i in passing if i not in neutral_all]
    chosen.extend(body[:count - len(chosen)])
    if len(chosen) < count:
        # A gamut so small (or a chart so large) that the body runs dry:
        # top up with the remaining reachable neutrals rather than shipping
        # a shorter chart than the reachable colours allow.
        have = set(chosen)
        rest = [i for i in passing if i not in have]
        chosen.extend(rest[:count - len(chosen)])

    for i in sorted(chosen):
        selection.targets.append((i, labs[i], tuple(device[i])))
    selection.corners = list(zip(CORNER_DEVICES, _corner_ideal_labs()))
    log.info("gamut selection: %d of %d master colours in gamut (%s margin), "
             "%d requested, %d chosen (%d neutral) + %d corners",
             selection.in_gamut_total, selection.master_total, margin,
             count, selection.achieved,
             sum(1 for t in selection.targets if t[0] in neutral_all),
             len(selection.corners))
    return selection


def flags_in_gamut(
    labs: "list[tuple[float, float, float]]",
    profile: Path,
    bin_dir: "str | Path",
    *,
    margin: str = MARGIN_SAFE,
    intent: str = "absolute",
    runner: "Callable[..., subprocess.CompletedProcess]" = subprocess.run,
) -> "list[bool]":
    """One in/out-of-gamut flag per Lab colour, same round trip and the same
    thresholds as :func:`select_gamut_targets` — Lab → B2A → device → A2B →
    Lab′; a reachable colour comes back within interpolation error, a clipped
    one lands on the gamut surface and moves far. Used by the measurement
    report's split statistics (Knut, 2026-08-10)."""
    from workflow.xicclu_runner import XiccluError, backward_device, forward_lab
    profile = Path(profile)
    if not profile.is_file():
        raise GamutTargetError(f"the profile file is missing: {profile}")
    threshold = MARGIN_THRESHOLD_DE76.get(margin)
    if threshold is None:
        raise GamutTargetError(f"unknown margin {margin!r}")
    letter = intent_letter(intent)
    try:
        device = backward_device(list(labs), profile, bin_dir, intent=letter,
                                 k_rule=None, runner=runner)
        back = forward_lab(device, profile, bin_dir, intent=letter,
                           runner=runner)
    except XiccluError as exc:
        raise GamutTargetError(str(exc)) from exc
    return [math.dist(lab, lab2) <= threshold
            for lab, lab2 in zip(labs, back)]



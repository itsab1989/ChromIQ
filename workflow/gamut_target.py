def write_gamut_ti1(selection: GamutSelection, out_path: Path) -> Path:
    """The chart's patch list: the chosen device values, corners last.

    Uses the battle-tested 3-table RGB emitter, so printtarg and the ChromIQ
    layout engine both accept the file exactly as they do any other .ti1.
    """
    from workflow.i1profiler_import import RgbPatch, write_ti1
    patches = [RgbPatch(*dev) for _i, _lab, dev in selection.targets]
    patches += [RgbPatch(*dev) for dev, _lab in selection.corners]
    if not patches:
        raise GamutTargetError("nothing to write — no colour is in gamut")
    return write_ti1(patches, Path(out_path))


def reference_rows(selection: GamutSelection):
    """(sample_id, device, Lab) in chart order — targets first, corners last,
    SAMPLE_ID 1..N matching :func:`write_gamut_ti1`'s order exactly."""
    rows = []
    sid = 1
    for _i, lab, dev in selection.targets:
        rows.append((sid, dev, lab))
        sid += 1
    for dev, lab in selection.corners:
        rows.append((sid, dev, lab))
        sid += 1
    return rows


def corner_sample_ids(selection: GamutSelection) -> "list[int]":
    n = len(selection.targets)
    return [n + 1 + i for i in range(len(selection.corners))]


def write_colorimetric_reference(selection: GamutSelection, out_path: Path) -> Path:
    """The stored colorimetric targets (§11 step 5) — one file, three jobs:
    the report's reference, the Print tab's force-Raw marker (feature A reads
    its presence), and the §5.4 record of set version, intent and margin."""
    from workflow.ti3_analysis import _lab_to_xyz_array
    import numpy as np
    rows = reference_rows(selection)
    corner_ids = corner_sample_ids(selection)
    labs = np.array([lab for _sid, _dev, lab in rows], dtype=float)
    xyzs = _lab_to_xyz_array(labs)          # 0..100, D50
    lines = [
        "CTI3   ",
        "",
        'DESCRIPTOR "ChromIQ colorimetric verification reference"',
        'ORIGINATOR "ChromIQ"',
        f'CREATED "{datetime.now().strftime("%a %b %d %H:%M:%S %Y")}"',
        'DEVICE_CLASS "OUTPUT"',
        'COLOR_REP "RGB_XYZ"',
        f'CHROMIQ_SET_VERSION "{selection.master_version}"',
        f'CHROMIQ_INTENT "{selection.intent}"',
        f'CHROMIQ_MARGIN "{selection.margin}"',
        f'CHROMIQ_MASTER_TOTAL "{selection.master_total}"',
        f'CHROMIQ_IN_GAMUT "{selection.in_gamut_total}"',
        f'CHROMIQ_REQUESTED "{selection.requested}"',
        f'CHROMIQ_CORNER_IDS "{" ".join(str(i) for i in corner_ids)}"',
        "",
        "NUMBER_OF_FIELDS 10",
        "BEGIN_DATA_FORMAT",
        "SAMPLE_ID RGB_R RGB_G RGB_B XYZ_X XYZ_Y XYZ_Z LAB_L LAB_A LAB_B",
        "END_DATA_FORMAT",
        "",
        f"NUMBER_OF_SETS {len(rows)}",
        "BEGIN_DATA",
    ]
    for (sid, dev, lab), xyz in zip(rows, xyzs):
        lines.append(" ".join(
            [str(sid)]
            + [f"{v:.4f}" for v in dev]
            + [f"{float(v):.4f}" for v in xyz]
            + [f"{float(v):.4f}" for v in lab]))
    lines += ["END_DATA", ""]
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    log.info("colorimetric reference written: %s (%d rows, %d corners)",
             out_path.name, len(rows), len(corner_ids))
    return out_path


def read_colorimetric_reference(path: Path) -> "dict | None":
    """{"labs": {sample_id_str: (L,a,b)}, "corner_ids": set[str], meta…} — or
    None when the file is missing or unreadable. Sample ids are strings, the
    same shape ``parse_ti3`` gives the report, so pairing needs no casts."""
    path = Path(path)
    if not path.is_file():
        return None
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    keywords: dict = {}
    fields: "list[str]" = []
    labs: dict = {}
    in_fmt = in_data = False
    for raw in text.splitlines():
        s = raw.strip()
        if not s:
            continue
        if s == "BEGIN_DATA_FORMAT":
            in_fmt = True
            continue
        if s == "END_DATA_FORMAT":
            in_fmt = False
            continue
        if s == "BEGIN_DATA":
            in_data = True
            continue
        if s == "END_DATA":
            in_data = False
            continue
        if in_fmt:
            fields += s.split()
            continue
        if in_data:
            cells = s.split()
            if len(cells) != len(fields):
                continue
            row = dict(zip(fields, cells))
            try:
                labs[row["SAMPLE_ID"]] = (float(row["LAB_L"]),
                                          float(row["LAB_A"]),
                                          float(row["LAB_B"]))
            except (KeyError, ValueError):
                continue
            continue
        if " " in s and s.split(None, 1)[1].startswith('"'):
            key, val = s.split(None, 1)
            keywords[key] = val.strip().strip('"')
    if not labs:
        return None
    corner_ids = set((keywords.get("CHROMIQ_CORNER_IDS") or "").split())
    return {
        "labs": labs,
        "corner_ids": corner_ids,
        "set_version": keywords.get("CHROMIQ_SET_VERSION", ""),
        "intent": keywords.get("CHROMIQ_INTENT", ""),
        "margin": keywords.get("CHROMIQ_MARGIN", ""),
        "master_total": keywords.get("CHROMIQ_MASTER_TOTAL", ""),
        "in_gamut": keywords.get("CHROMIQ_IN_GAMUT", ""),
    }


def mark_chart_as_colorimetric(ti2_path: Path, reference_path: Path) -> None:
    """Record the reference in the chart's ``.channels.json`` sidecar, so a
    chart whose reference file goes missing still *claims* one — feature A's
    A3c case, which forces Raw rather than risking a double conversion."""
    sidecar = Path(ti2_path).with_name(f"{Path(ti2_path).stem}.channels.json")
    data: dict = {}
    if sidecar.is_file():
        try:
            data = json.loads(sidecar.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            data = {}
    data["colorimetric_reference"] = Path(reference_path).name
    try:
        sidecar.write_text(json.dumps(data, indent=2), encoding="utf-8")
    except OSError:
        log.warning("could not mark %s as colorimetric", sidecar, exc_info=True)

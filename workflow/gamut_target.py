@dataclass
class GamutSelection:
    """The outcome of filtering the master set through one profile."""

    master_version: str
    master_total: int             #: size of the master set
    in_gamut_total: int           #: coverage — reachable master colours
    requested: int                #: what the user asked for
    intent: str                   #: "absolute" | "relative"
    margin: str                   #: "safe" | "full"
    #: The chart's colours, in candidate-list order: (master_index, master Lab,
    #: device 0..100). len == min(requested, in_gamut_total).
    targets: "list[tuple[int, tuple[float, float, float], tuple[float, ...]]]" = field(default_factory=list)
    #: The §9a corners: (device, ideal sRGB Lab), appended after the targets.
    corners: "list[tuple[tuple[float, ...], tuple[float, float, float]]]" = field(default_factory=list)
    #: #182 A11 (Knut, 5817809396): the paper THE PROFILE DESCRIBES, its media
    #: white (``wtpt``) as L*a*b* D50, and the profile's file name. The row
    #: "Paper white, difference from the reference paper" compares the bare
    #: paper of the printed chart with this, so it asks "is this the paper the
    #: profile was made for". None when the profile carries no media white.
    profile_white_lab: "tuple[float, float, float] | None" = None
    profile_name: str = ""
    #: How the body was spread (:data:`SPREADS`); ``grid`` only when the
    #: experimental stepwise grid was asked for, with its search history
    #: ``[(spacing, count)]``.
    spread: str = "even"
    grid_history: list = field(default_factory=list)

    @property
    def achieved(self) -> int:
        return len(self.targets)

    @property
    def total_patches(self) -> int:
        return len(self.targets) + len(self.corners)


def profile_media_white_lab(profile: "Path | str"
                            ) -> "tuple[float, float, float] | None":
    """The profile's media white (its ``wtpt`` tag) as L*a*b* D50, rounded to
    four places, or None when the file has no readable one (#182 A11).

    This is the paper the profile was measured on: what a bare patch of that
    paper reads, in absolute colorimetry. Never raises."""
    try:
        from workflow.icc_info import read_icc
        lab = read_icc(Path(profile)).white_lab
    except Exception:                                  # noqa: BLE001
        return None
    if lab is None:
        return None
    return tuple(round(float(v), 4) for v in lab)


def load_master_labs(path: "Path | None" = None) -> "list[tuple[float, float, float]]":
    """The candidate colours as Lab (D50).

    With no *path*, the 4.3.5 list (``PROVISIONAL-r2``): the 5,960 colours of
    the published sRGB set, in its order, then the 10,648 of
    :func:`wide_cube_labs`. With a *path*, that one file only (a test's set,
    or the r1 file on its own).

    The sRGB set is generated with an sRGB conditioning profile, so targen's XYZ
    column is D65-referenced; it is Bradford-adapted to D50 here with exactly
    the machinery the measurement report uses for design values, so the
    targets and the report speak the same white point.
    """
    from workflow.measurement_report import (_bradford_d65_to_d50,
                                             _design_xyz_is_d65,
                                             _design_xyz_to_100)
    from workflow.ti3_analysis import parse_ti3, xyz_to_lab
    import numpy as np
    if path is None:
        # k83: the published sRGB set, then the wide cube.
        return load_master_labs(master_set_path()) + wide_cube_labs()
    p = Path(path)
    if not p.is_file():
        raise GamutTargetError(
            f"the master colour set is missing: {p.name}")
    data = parse_ti3(p)
    xyz = _design_xyz_to_100(np.asarray(data.xyz, dtype=float))
    adapt = _design_xyz_is_d65(data.keywords)
    out = []
    for x, y, z in xyz:
        if adapt:
            x, y, z = _bradford_d65_to_d50(float(x), float(y), float(z))
        out.append(xyz_to_lab((float(x) / 100.0, float(y) / 100.0,
                               float(z) / 100.0)))
    return out


#: ProPhoto RGB (ROMM RGB, ISO 22028-2): primaries and the D50 white.
_PROPHOTO_PRIMARIES = ((0.7347, 0.2653), (0.1596, 0.8404), (0.0366, 0.0001))
_D50_WHITE = (0.9642, 1.0, 0.8249)


def _prophoto_to_xyz_matrix():
    """Linear ProPhoto RGB -> XYZ (D50, Y of white = 1)."""
    import numpy as np
    cols = np.array([[x / y, 1.0, (1.0 - x - y) / y]
                     for x, y in _PROPHOTO_PRIMARIES]).T
    scale = np.linalg.solve(cols, np.asarray(_D50_WHITE))
    return cols * scale


def wide_cube_labs(steps: int = WIDE_CUBE_STEPS
                   ) -> "list[tuple[float, float, float]]":
    """The wide part of the candidate list (k83): every colour of a
    *steps* x *steps* x *steps* cube in **ProPhoto RGB**, as Lab D50, red
    slowest, blue fastest.

    Knut, #182 6102031563: the list "should contain colors that any
    professional printer may achieve. That possibly means even larger than
    AdobeRGB1998 [...] a whole cube of 22x22x22 (10648 colors)". ProPhoto RGB
    contains sRGB and Adobe RGB (1998) and every surface colour a printer can
    put on paper; measured on Basti's ET-8550 glossy profile, 21.8 % of the
    printer's gamut volume lies outside sRGB, 6.9 % outside Adobe RGB, none
    outside ProPhoto RGB. Many of the cube's colours are no surface colour at
    all (its primaries lie outside the spectral locus); no profile reaches
    them, so the gamut filter drops them like any other unreachable colour.

    ROMM RGB's own transfer curve: linear below 1/32 (encoded), gamma 1.8
    above. Computed, not read from a file, so the list cannot drift from this
    definition; it is deterministic to the last bit on one machine."""
    import numpy as np
    g = np.linspace(0.0, 1.0, int(steps))
    r, gg, b = np.meshgrid(g, g, g, indexing="ij")
    rgb = np.stack([r.ravel(), gg.ravel(), b.ravel()], axis=1)
    lin = np.where(rgb < 1.0 / 32.0, rgb / 16.0, rgb ** 1.8)
    xyz = lin @ _prophoto_to_xyz_matrix().T
    t = xyz / np.asarray(_D50_WHITE)
    d = 6.0 / 29.0
    f = np.where(t > d ** 3, np.cbrt(t), t / (3.0 * d * d) + 4.0 / 29.0)
    lab = np.stack([116.0 * f[:, 1] - 16.0, 500.0 * (f[:, 0] - f[:, 1]),
                    200.0 * (f[:, 1] - f[:, 2])], axis=1)
    # Exact neutrals: R=G=B is the D50 white's own chromaticity, so a* and b*
    # are 0 but for arithmetic dust, which is cleared so the grey axis reads
    # as neutral to every check.
    neutral = (rgb[:, 0] == rgb[:, 1]) & (rgb[:, 1] == rgb[:, 2])
    lab[neutral, 1:] = 0.0
    return [(float(L), float(a), float(bb)) for L, a, bb in lab]



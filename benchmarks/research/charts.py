"""Charts the battery builds on (battery v3, Agent 16).

Protocol v3 (Validation/protocol-v3.md, section C) scores every printer on
charts ChromIQ really produces, because the chart decides what a forward
model can learn (Agent 13, K2: on a real targen chart the combined design's
highlight neutral was 3x worse than on the battery's ramp-rich chart).

Compositions (``kind``):

* ``targen``     Argyll targen at ChromIQ's defaults (what the Create Chart
                 tab sends when nothing is changed): ``-d<device> -f<N>
                 -e<auto> -B<auto> -G -g<auto>``, single channel steps 0
                 (``-s`` is not sent), NO ink limit (``-l`` is an expert row
                 that is off by default). The Auto white/black/grey counts
                 follow ``workflow.chart_creator.manual_neutrals`` (Auto is on
                 by default). PRIMARY for every printer.
* ``ecg``        Agent 14's ECG-composed chart (``datasets.make_chart_ecg``):
                 what professional N-colour charts sample. PRIMARY for 5+ inks
                 beside ``targen``.
* ``september``  the September battery chart (11-step single-ink ramps on
                 every channel, a composite grey, corners, Halton fill).
                 ROBUSTNESS only: ChromIQ never produces it, so its rows may
                 veto a candidate but can never make one BETTER.

The targen charts are generated once and committed under
``benchmarks/research/data/charts/`` (deterministic, but targen is an
external binary: the committed file IS the chart, whatever a future targen
does). ``ensure_targen`` regenerates a missing one and records the command.

Measured while building this (Argyll 3.5.0, 2026-10-04): with ``-d4`` any
``-g`` (grey steps) together with ``-l`` (ink limit) aborts in OFPS
("node vertex info should be empty on add_node2voronoi() entry"); ``-l``
alone or ``-g`` alone work. ChromIQ's default sends ``-g`` and not ``-l``.
"""
from __future__ import annotations

import math
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

import numpy as np

ARGYLL = "/Applications/Argyll/bin"
DATA = Path(__file__).resolve().parent / "data" / "charts"

# Device representation -> targen -d code (+ -D colorant toggles).
# -D takes targen's colorant number (targen -??): 5 Orange, 9 Violet.
TARGEN_DEVICE = {
    "RGB": ["-d2"], "CMY": ["-d5"], "CMYK": ["-d4"],
    "CMYKcm": ["-d6"], "CMYKcmk": ["-d7"], "CMYKRB": ["-d8"],
    "CMYKOG": ["-d9"], "CMYKRGB": ["-d10"], "CMYKOGV": ["-d11"],
    "CMYKOGB": ["-d12"], "CMYKO": ["-d4", "-D5"], "CMYKV": ["-d4", "-D9"],
    "CMYKOV": ["-d4", "-D5", "-D9"],
}

CHART_KINDS = ("targen", "ecg", "september")
# what a chart's rows may do (protocol v3, C3)
CHART_ROLE = {"targen": "primary", "ecg": "primary", "september": "robustness"}

# ChromIQ's Auto neutral counts (workflow/chart_creator.py: REF_BUDGET 560,
# grey 32 x effective sheets in [8, 128], white/black 4 x 1.5^log2(eff) in
# [2, 8]). Restated here so the benchmark does not import the app's UI layer;
# tests/test_benchmarks_research_v3.py pins it to the app's function.
REF_BUDGET = 560


def chromiq_auto_neutrals(total_patches: int) -> tuple[int, int, int]:
    eff = total_patches / REF_BUDGET
    grey = max(8, min(128, round(32 * eff)))
    factor = 1.5 ** math.log2(eff) if eff > 0 else 0.0
    wb = max(2, min(8, round(4 * factor)))
    return grey, wb, wb


def targen_args(device_rep: str, patches: int) -> list[str]:
    grey, white, black = chromiq_auto_neutrals(patches)
    return [*TARGEN_DEVICE[device_rep], f"-f{patches}", f"-e{white}",
            f"-B{black}", "-G", f"-g{grey}"]


def chart_name(device_rep: str, patches: int) -> str:
    return f"targen-{device_rep}-n{patches}"


def ensure_targen(device_rep: str, patches: int, argyll: str = ARGYLL,
                  data: Path = DATA) -> Path:
    """The committed .ti1 for this chart, generated by targen if missing."""
    data.mkdir(parents=True, exist_ok=True)
    out = data / f"{chart_name(device_rep, patches)}.ti1"
    if out.exists():
        return out
    args = targen_args(device_rep, patches)
    with tempfile.TemporaryDirectory() as td:
        r = subprocess.run([f"{argyll}/targen", *args, "chart"], cwd=td,
                           capture_output=True, text=True, timeout=1800)
        src = Path(td) / "chart.ti1"
        if r.returncode != 0 or not src.exists():
            raise RuntimeError(f"targen {' '.join(args)} failed: "
                               f"{(r.stderr or r.stdout)[-400:]}")
        text = src.read_text(encoding="utf-8", errors="replace")
        # stamp the command; drop the creation time so the file is stable
        text = re.sub(r'CREATED\s+"[^"]*"\n', "", text)
        text = text.replace('ORIGINATOR "Argyll targen"',
                            'ORIGINATOR "Argyll targen"\nKEYWORD "CHROMIQ_BENCH_COMMAND"\n'
                            f'CHROMIQ_BENCH_COMMAND "targen {" ".join(args)}"', 1)
        tmp = out.with_suffix(".tmp")
        tmp.write_text(text, encoding="utf-8")
        shutil.move(str(tmp), out)
    return out


def read_ti1(path: Path) -> tuple[str, np.ndarray]:
    """-> (device_rep, device values 0..1) of a targen .ti1."""
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    rep = re.search(r'COLOR_REP\s+"([^"]+)"', text).group(1)
    fmt = re.search(r"BEGIN_DATA_FORMAT\s+(.*?)\s+END_DATA_FORMAT", text, re.S).group(1).split()
    body = re.search(r"BEGIN_DATA\s*\n(.*?)\nEND_DATA", text, re.S).group(1)
    prefix = "RGB" if rep == "iRGB" else rep
    cols = [i for i, f in enumerate(fmt) if f.startswith(prefix + "_")]
    rows = [ln.split() for ln in body.splitlines() if ln.strip()]
    dev = np.array([[float(r[i]) for i in cols] for r in rows]) / 100.0
    return ("RGB" if rep == "iRGB" else rep), dev


def targen_chart(device_rep: str, patches: int) -> np.ndarray:
    rep, dev = read_ti1(ensure_targen(device_rep, patches))
    if rep != device_rep:
        raise ValueError(f"chart rep {rep} != {device_rep}")
    return dev


def chart_for(printer, kind: str, n_patches: int, seed: int = 11) -> np.ndarray:
    """Device values of a chart of composition ``kind`` for ``printer``."""
    from benchmarks.research import datasets as dsm
    if kind == "targen":
        return targen_chart(printer.device_rep, n_patches)
    if kind == "ecg":
        if not hasattr(dsm, "make_chart_ecg"):
            raise RuntimeError("datasets.make_chart_ecg (agent 14) is missing")
        return dsm.make_chart_ecg(printer, n_patches, seed)
    if kind == "september":
        return dsm.make_chart(printer, n_patches, seed)
    raise KeyError(kind)


def composition(dev: np.ndarray, additive: bool) -> dict:
    """What a chart samples: share of patches by inks on, single-ink patches
    per channel and how many of them are light (<= 12 %), paper patches."""
    ink = (1.0 - dev) if additive else dev
    on = ink > 1e-6
    k = on.sum(1)
    single = k == 1
    return {"patches": int(len(dev)),
            "paper": int((k == 0).sum()),
            "inks_on_share": {int(i): float(np.mean(k == i)) for i in range(dev.shape[1] + 1)},
            "single_ink_per_channel": [int((single & on[:, c]).sum()) for c in range(dev.shape[1])],
            "single_ink_le12_per_channel": [int((single & on[:, c] & (ink[:, c] <= 0.12)).sum())
                                            for c in range(dev.shape[1])],
            "max_total_ink_pct": float(ink.sum(1).max() * 100)}

"""An i1iO chart of SEVERAL pages, measured with i1Profiler's "Measure Chart"
one sheet at a time (the i1iO Beta, 2026-11-16; design and challenge in
``ChromIQ-work/2026-11-16_i1io_multipage_import/``).

HONEST ABOUT THE DATA: no real Measure Chart file of a sheet of a multi-page
chart exists. Every file here is GENERATED by the forward model
(`tests/i1p_forward.py`), whose file shape is copied from the one real file
there is, a single-sheet scan; each sheet of a chart is scanned as a sheet of
its own (`load_sheet(ti2, page)`).

What is pinned: each file goes to its own page by its grid and its colours,
never a typed number and never a guess; a wrong or doubtful file is refused
or asked about; the run's measurement is written only when every page is in,
and it then holds every patch once, each reading on its own patch; with the
Beta off nothing of this runs.
"""

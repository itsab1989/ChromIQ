def test_beta_off_is_todays_refusal_and_no_new_code_path(
        charts, tmp_path, qapp, monkeypatch):
    from workflow.i1io import pages as P
    from workflow.i1io import support
    before = support._latched
    support.set_enabled_for_this_process(True)
    s, fm, ctl, run = _profiling(tmp_path, charts["two"])
    f = _sheet_file(run.chart_ti2, 1, tmp_path / "p1.cmxf")
    support.set_enabled_for_this_process(False)
    for name in ("applies", "match_file", "pages_state", "page_count"):
        monkeypatch.setattr(P, name, lambda *a, **k: pytest.fail("reached"))
    tab = _tab(s, fm, ctl)
    rec = _drive(tab, monkeypatch)
    try:
        tab._switch_mode("import")
        assert tab._import_takes_pages(run) is False
        _import(tab, f)
        tab._update_import_panel()
    finally:
        tab.deleteLater()
        support._latched = before
    # today: a .cmxf is not a file the converter takes
    assert rec["info"] and "could not be converted" in rec["info"][0][0]
    assert not run.i1io_pages_dir.exists()
    assert not run.measurement_ti3.exists()



def test_the_ruler_lights_and_conditions_betas_change_nothing(
        charts, tmp_path, qapp, beta_on, monkeypatch):
    """They act inside a chartread session; this import never reads them:
    the stored page is byte for byte the same with them on and off."""
    out = []
    for on in (False, True):
        d = tmp_path / ("on" if on else "off")
        d.mkdir()
        s, fm, ctl, run = _profiling(d, charts["two"])
        for key in ("ruler_check_beta", "i1pro2_lights_beta",
                    "i1pro3_conditions_beta"):
            s.set(key, on)
        tab = _tab(s, fm, ctl)
        _drive(tab, monkeypatch)
        try:
            tab._switch_mode("import")
            _import(tab, _sheet_file(run.chart_ti2, 1, tmp_path / "same.cmxf"))
        finally:
            tab.deleteLater()
        out.append(run.i1io_page_ti3(1).read_bytes())
    assert out[0] == out[1]
    import inspect
    from workflow.i1io import pages as P
    src = inspect.getsource(P)
    for key in ("ruler", "lights", "conditions_beta", "settings"):
        assert key not in src.lower().replace("nothing here reads a setting",
                                              "")


def test_texts_have_no_em_dash_and_no_open_placeholder():
    from workflow import measurement_messages as M
    sheets = [{"page": 1, "pages": 2, "cols": 24, "rows": 22, "p1": "A1",
               "p2": "V1", "p3": "V24"},
              {"page": 2, "pages": 2, "cols": 24, "rows": 8, "p1": "W1",
               "p2": "AD1", "p3": "AD24", "labelled": False}]
    title, body = M.i1io_measure_chart_pages_window(sheets, True, False)
    texts = [title, body, *M.i1io_page_filed_window([2], 2, [1]),
             *M.i1io_page_filed_window([1, 3], 4, [2, 4]),
             M.i1io_pages_panel_text(3, [1], [2, 3], False),
             M.i1io_pages_panel_text(3, [1, 2, 3], [], True)]
    for code in ("no-grid", "on-page", "none", "condition", "instrument",
                 "unit", "twice", "not-mc", "verify"):
        texts.append(M.i1io_pages_reason(code, grids=[(1, 24, 22)],
                                         pages=[1, 2], reason="x"))
    for t in texts:
        assert "—" not in t and "{" not in t, t
    assert "24 columns and 8 rows" in body and "W1" not in body
    assert "A1, V1 and V24" in body

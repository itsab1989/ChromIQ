def test_every_page_order_gives_one_and_the_same_measurement(
        charts, tmp_path, beta_on):
    from core.file_manager import Run
    from workflow.i1io import measure_chart as MC
    from workflow.i1io import pages as P
    ti2 = charts["three"]
    filed = {}
    for page in (1, 2, 3):
        cx = _sheet_file(ti2, page, tmp_path / f"p{page}.cmxf")
        conv = F.convert(cx, tmp_path / f"c{page}")
        m = P.match_file(cx, conv, ti2)
        assert MC.complete(conv, ti2, m.verdict)
        filed[page] = (cx, conv)
    results = set()
    for order in itertools.permutations((1, 2, 3)):
        rdir = tmp_path / ("run_" + "".join(map(str, order)))
        rdir.mkdir()
        run = Run.for_dir(rdir)
        for page in order:
            cx, conv = filed[page]
            st = P.stage_page(ti2, page, conv, cx, 3,
                              tmp_path / f"s{page}.ti3")
            P.store_staged(run, ti2, page, st)
            assert P.pages_state(run, ti2).complete == (page == order[-1])
        out = rdir / "merged.ti3"
        assert P.merge_pages(run, ti2, out) == 1320
        results.add(out.read_bytes())
    assert len(results) == 1
    _assert_every_reading_on_its_patch(out, ti2)



def test_a_newer_file_for_a_page_is_asked_and_the_old_one_kept(
        charts, tmp_path, qapp, beta_on, monkeypatch):
    s, fm, ctl, run = _profiling(tmp_path, charts["two"])
    tab = _tab(s, fm, ctl)

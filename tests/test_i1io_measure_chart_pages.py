def test_page_two_first_then_page_one(charts, tmp_path, qapp, beta_on,
                                      monkeypatch):
    """The owner's case: the partial state in words, Build Profile refused
    with the pages still to come, then the whole measurement."""
    s, fm, ctl, run = _profiling(tmp_path, charts["two"])
    tab = _tab(s, fm, ctl)
    rec = _drive(tab, monkeypatch)
    try:
        tab._switch_mode("import")
        _import(tab, _sheet_file(run.chart_ti2, 2, tmp_path / "sheet2.cmxf"))
        assert not rec["refused"], rec["refused"]
        assert not run.measurement_ti3.exists()
        assert run.i1io_page_ti3(2).is_file()
        assert not run.i1io_page_ti3(1).exists()
        assert len(rec["filed"]) == 1
        assert "Still to import: page 1." in rec["filed"][0][1]
        panel = tab._import_box_body.text()
        assert "Imported so far: page 2." in panel
        assert "Still to import: page 1." in panel
        # Build Profile says it in words
        from core.argyll_runner import ArgyllRunner
        from ui.tabs.tab_profile import TabProfile
        prof = TabProfile(ArgyllRunner(s), s)
        prof.set_target_controller(ctl)
        prof._say_i1io_pages_missing()
        # on the tab itself: the Build button is greyed without a
        # measurement, so the file line and its tooltip say it
        assert "Still to import: page 1." in prof._file_lbl.text()
        assert "not every page is imported yet" in prof._build_btn.toolTip()
        said = []
        monkeypatch.setattr(prof, "_show_tool_failure_dialog",
                            lambda t, b: said.append((t, b)))
        prof._on_build()
        assert said and "Still to import: page 1." in said[0][1]
        prof.deleteLater()
        # page 1 completes it
        _import(tab, _sheet_file(run.chart_ti2, 1, tmp_path / "sheet1.cmxf"))
        assert not rec["refused"], rec["refused"]
        assert len(rec["done"]) == 1
    finally:
        tab.deleteLater()
    assert run.measurement_ti3.is_file()
    text = run.measurement_ti3.read_text(encoding="utf-8")
    assert 'CHROMIQ_I1IO_PAGES "2"' in text
    _assert_every_reading_on_its_patch(run.measurement_ti3, run.chart_ti2)
    assert run.i1io_page_ti3(1).is_file() and run.i1io_page_ti3(2).is_file()



def _sheet_file(ti2: Path, page: int, path: Path, lay: str = "right",
                seed: int = 0, **kw) -> Path:
    sh = F.load_sheet(ti2, page)
    return F.measure(sh, path, F.mistakes(sh)[lay],
                     rng=np.random.default_rng(seed + 10 * page), **kw)


def _profiling(tmp_path: Path, ti2: Path):
    """A project whose run 1 holds *ti2* (and its side file) as its chart,
    the bar on it, profiling."""
    s, fm, ctl = _env(tmp_path)
    run = fm.project().run("run1")
    stem = ti2.name[:-4]
    for p in ti2.parent.iterdir():
        if p.is_file() and p.name.startswith(stem + "."):
            shutil.copy2(p, run.dir / (run.stem + p.name[len(stem):]))
    ctl.set_profile_run("run1")
    return s, fm, ctl, run


def _drive(tab, monkeypatch, answer=True, page=None):
    rec = {"refused": [], "filed": [], "asked": [], "which": [], "done": [],
           "info": []}
    monkeypatch.setattr(tab, "_show_import_refusal",
                        lambda m, **kw: rec["refused"].append((m.id, kw)))
    monkeypatch.setattr(tab, "_say_page_filed",
                        lambda t, b: rec["filed"].append((t, b)))
    monkeypatch.setattr(tab, "_ask_import_question",
                        lambda m, *a, **k: rec["asked"].append(m.id)
                        or answer)
    monkeypatch.setattr(tab, "_ask_which_page",
                        lambda name, choices, chart:
                        rec["which"].append(tuple(choices)) or page)
    monkeypatch.setattr(tab, "_show_import_done_profiling",
                        lambda run, dst: rec["done"].append(dst))
    monkeypatch.setattr(tab, "_say_on_screen",
                        lambda t, b: rec["info"].append((t, b)))
    monkeypatch.setattr(tab, "_ask_how_printed", lambda *a: None)
    return rec


def _import(tab, *files):
    if len(files) == 1:
        tab._use_import_file(files[0])
    else:
        tab._use_import_files(list(files))
    tab._on_import_measurement()


def _assert_every_reading_on_its_patch(ti3: Path, ti2: Path):
    """The whole chart once, the chart's device values by id, and each
    reading's colour the colour printed on ITS patch (the forward model's
    printer, noise-free): close for the own patch, far for a shuffle."""
    from workflow.ti3_analysis import parse_ti3
    from workflow.turned_colour_check import _lab
    filed = parse_ti3(ti3)
    sh = F.load_sheet(ti2, 1)
    ids = [int(str(s).strip('"')) for s in filed.sample_ids]
    assert sorted(ids) == sorted(sh.rgb_of), "every patch exactly once"
    for sid, rgb in zip(ids, filed.rgb):
        assert np.allclose(rgb, sh.rgb_of[sid], atol=1e-3)
    lab = _lab(np.asarray(filed.xyz, float), np.array([96.42, 100.0, 82.49]))
    want = np.array([F.printer_lab(sh.rgb_of[s], None, 0.0) for s in ids])
    d = np.linalg.norm(lab - want, axis=1)
    shuffled = np.linalg.norm(lab - np.roll(want, 37, axis=0), axis=1)
    assert np.median(d) < 4.0 and np.percentile(d, 99) < 10.0, (
        np.median(d), d.max())
    assert np.median(shuffled) > 4 * np.median(d)



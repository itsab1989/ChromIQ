        tab._switch_mode("import")
        _import(tab, _sheet_file(run.chart_ti2, 1, tmp_path / "a.cmxf"))
        first = run.i1io_page_ti3(1).read_bytes()
        newer = _sheet_file(run.chart_ti2, 1, tmp_path / "b.cmxf", seed=5)
        _import(tab, newer)                       # Cancel: nothing changes

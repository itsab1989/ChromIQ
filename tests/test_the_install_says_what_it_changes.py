def _all_text() -> str:
    return sd.usb_certificate_notice_line() + sd.usb_certificate_details_text()


def test_it_never_says_the_certificate_is_trusted_for_everything():
    """THE ONE MEASURABLY FALSE CLAIM, AND IT WAS WRITTEN ONCE ALREADY.

    A draft said "a certificate in the Trusted Root list is trusted for
    everything, not only for drivers". It is not. Extension 2.5.29.37 on the
    certificate on this bench is marked CRITICAL and contains exactly one
    purpose — Code Signing, 1.3.6.1.5.5.7.3.3 — which Windows must honour, so it
    cannot vouch for a web site, an e-mail or a client identity. libwdi's
    `pki.c:723,749` agrees.

    That draft was wrong in the SCARY direction, inside a change whose whole
    subject is telling the truth about the install. It would have read, to a
    photographer mid-repair, as a root-CA compromise.
    """
    text = _all_text().lower()
    for claim in ("trusted for everything",
                  "for anything at all",
                  "trusted for any purpose"):
        assert claim not in text, claim
    # …and the limit is stated, not merely not-denied.
    assert "cannot vouch for a website" in sd.usb_certificate_details_text()


def test_the_removal_advice_is_hedged_because_the_experiment_was_not_run():
    """Deleting the certificate and rebooting was NOT tested.

    Two things point the same way — `libusb0.sys` carries its own signatures
    from Microsoft and from its authors, and two driver packages on the bench
    whose certificates libwdi had already deleted are still enumerated — but
    "enumerated" is not "starts after a reboot", and the exact experiment would
    have meant modifying a certificate store on a working bench. So the window
    says what is expected, and says that it is only what is expected.
    """
    text = sd.usb_certificate_details_text()
    assert "we can tell you what we expect" in text
    assert "not that we have proved it" in text
    assert "was not tested" in text


def test_it_does_not_promise_a_repair_nobody_has_produced():
    """"Running Install Driver again puts everything back" was a repair promise
    for a failure mode nobody has ever produced. What is known is only that a
    second install mints a fresh certificate and reinstalls the driver."""
    assert "puts everything back" not in _all_text()


def test_the_replacement_claim_is_scoped_to_one_instrument():
    """libwdi deletes the certificate with the SAME SUBJECT, and the subject is
    the hardware ID — so it is one certificate per instrument, not one per
    machine. This bench holds two. And `_show_usb_installer` runs the install
    over every unbound instrument, so one click by a two-instrument owner
    creates two."""
    text = sd.usb_certificate_details_text()
    assert "for the same instrument" in text
    assert "a different instrument gets its own" in text


def test_the_scope_of_the_measurement_is_stated():
    """ARM64, `--type 1`, one instrument. Not "Windows"."""
    text = sd.usb_certificate_details_text()
    assert "ARM64" in text
    assert "one machine is what was checked" in text


def test_the_argyll_comparison_is_the_measured_one():
    """`ArgyllCMS_install_USB.exe` is itself a libwdi program — it carries
    `wdi_prepare_driver`, `CreateSelfSignedCert`, `CN=%s (libwdi
    autogenerated)` and the literal `Added certificate '%s' to 'Root' and
    'TrustedPublisher' stores` — and `CN=ArgyllCMS (libwdi autogenerated)` is in
    both stores on this bench, from 2026-05-08. The window may say so because it
    was measured, not because it sounds reassuring."""
    text = sd.usb_certificate_details_text()
    assert "ArgyllCMS (libwdi autogenerated)" in text
    assert "ArgyllCMS's own USB driver installer does exactly this" in text


def test_it_tells_the_user_how_to_look_and_how_to_remove():
    """The owner asked for both, in concrete steps."""
    text = sd.usb_certificate_details_text()
    assert "certlm.msc" in text
    assert "Trusted Root Certification Authorities" in text
    assert "Trusted Publishers" in text
    assert "right-click the certificate" in text


def test_the_search_term_it_gives_survives_the_path_wrapper():
    r"""`_driver_notice` runs its text through `_let_paths_wrap`, which inserts
    U+200B after every backslash. A user told to search for
    `USB\VID_0765&PID_6008 (libwdi autogenerated)` would copy an invisible
    character into certlm's find box and match nothing. The tail it actually
    names has no backslash — and no ampersand, which is the other way a rich
    text window eats a name."""
    text = sd.usb_certificate_details_text()
    assert "(libwdi autogenerated)" in text
    assert "\\" not in text
    assert not re.search(r"&(?!amp;|nbsp;|lt;|gt;)", text)



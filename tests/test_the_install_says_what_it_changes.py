r"""The driver install writes a certificate to the machine. The window says so.

MEASURED READ-ONLY ON THE ARM64 BENCH, 2026-09-06. `Install Driver` at 06:43:28
produced `CN=USB\VID_0765&PID_6008 (libwdi autogenerated)` in BOTH
`Cert:\LocalMachine\Root` and `…\TrustedPublisher`, `NotBefore` 06:43:31 — three
seconds later, and five minutes after the only other driver install that
evening. `core/usb_driver_installer.py` carries the full evidence beside
`WDI_DRIVER_TYPE`, including why no option of wdi-simple's can turn it off.

The window used to say nothing about it. These are the guards that keep it
saying something, and each one is here because leaving it out would let a
specific, named failure back in:

* the paragraph appears BEFORE the click, not only behind a button;
* it carries the three load-bearing facts (which lists, whose computer, that it
  stays behind) rather than deferring all of them;
* the button and the paragraph appear together, in every hardware shape;
* the Zadig branch gets the disclosure too, because Zadig is libwdi;
* and nothing in the extensive text claims more than was measured — in
  particular that the certificate is unrestricted, which is FALSE (its Extended
  Key Usage is critical and is Code Signing alone), and that removing it later
  is safe, which is UNTESTED.
"""
from __future__ import annotations

import re
from types import SimpleNamespace

import pytest

from ui.dialogs import settings_dialog as sd

ALL_CODES = ["de", "es", "fr", "it", "ja", "nl", "no", "pl", "pt", "ru", "sv",
             "zh_CN"]


def dev(name: str, has_winusb: bool):
    return SimpleNamespace(name=name, has_winusb=has_winusb)


I1PRO = "GretagMacbeth i1 Pro / i1 Pro 2"
SPYDER = "Datacolor SpyderX"

#: Every shape of the USB half, and whether a driver is about to be installed
#: for anything in it. The pairing of the paragraph and the button is asserted
#: over ALL of them rather than over the one that was in mind while writing it.
SHAPES = [
    ([], True, False),
    ([], False, False),
    ([dev(I1PRO, False)], True, True),
    ([dev(I1PRO, False)], False, True),
    ([dev(I1PRO, True)], True, False),
    ([dev(I1PRO, True)], False, False),
    ([dev(I1PRO, True), dev(SPYDER, True)], True, False),
    ([dev(I1PRO, False), dev(SPYDER, False)], True, True),
    ([dev(I1PRO, True), dev(SPYDER, False)], True, True),
    ([dev(I1PRO, False), dev(SPYDER, True)], False, True),
]


# ---------------------------------------------------------------------------
# 1. It is said before the click
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("devices,wdi,expected", SHAPES)
def test_the_paragraph_and_the_button_always_appear_together(
        devices, wdi, expected):
    """Neither half means anything alone.

    A paragraph that says "click <b>What this changes…</b>" beside a window with
    no such button sends the user hunting for a control that is not there; a
    button beside a paragraph that never mentions a certificate explains
    something nobody was told about. `usb_shows_certificate_details` is what
    `_show_usb_installer` builds the button from, so this ties the two to one
    another over every hardware shape instead of trusting them to stay equal.
    """
    msg, _ = sd.usb_installer_text(devices, wdi_available=wdi)
    in_text = sd.usb_certificate_notice_line() in msg
    assert sd.usb_shows_certificate_details(devices, wdi) is expected
    assert in_text is expected, (devices, wdi)


def test_the_disclosure_is_in_the_first_window_not_only_behind_the_button():
    """The whole placement decision, as an assertion.

    If this ever fails because somebody moved the paragraph into
    `usb_certificate_details_text()` to shorten the window, the disclosure has
    become a footnote: a user who presses Install Driver without opening
    anything else would then have been told nothing.
    """
    msg, _ = sd.usb_installer_text([dev(I1PRO, False)], wdi_available=True)
    assert "certificate" in msg


@pytest.mark.parametrize("phrase", [
    # which lists it goes into
    "lists of trusted signers",
    # whose computer trusts it
    "for the whole computer",
    # and that it does not go away with the driver
    "It stays there after the driver is gone",
])
def test_the_three_load_bearing_facts_are_before_the_click(phrase):
    """The first draft deferred all three to the details window.

    It said only that "a small security certificate" is added to "your
    computer's list of trusted certificates" — which never says *root*, never
    says the whole machine trusts it, and never says it stays behind. Those
    three ARE the disclosure. Everything else may live behind the button.
    """
    msg, _ = sd.usb_installer_text([dev(I1PRO, False)], wdi_available=True)
    assert phrase in msg, phrase


def test_the_zadig_branch_is_disclosed_too_because_zadig_is_libwdi():
    """The hole the first draft left, named.

    Without the bundled wdi-simple this window installs nothing — it sends the
    user to Zadig, and Zadig is libwdi's own front end; libwdi's Certification
    Practice Statement names it first among the applications that install these
    certificates. Keying the disclosure on `wdi_available` would have told
    exactly the users ChromIQ installs for, and none of the users it sends
    elsewhere.
    """
    msg, btn = sd.usb_installer_text([dev(I1PRO, False)], wdi_available=False)
    assert btn == "Open Zadig"
    assert sd.usb_certificate_notice_line() in msg


def test_the_disclosure_does_not_reach_a_user_who_is_installing_nothing():
    """The other direction, and it is not symmetry for its own sake.

    Every device already driven means the button says `Reinstall Driver` and
    nothing is about to be written. A certificate paragraph there would be
    describing something that is not happening.
    """
    for wdi in (True, False):
        msg, _ = sd.usb_installer_text([dev(I1PRO, True)], wdi_available=wdi)
        assert "certificate" not in msg



def test_the_rich_text_is_balanced():
    """Every tag opened is closed. A stray `<` swallows everything up to the
    next `>` SILENTLY — measured on this Qt: `'5 < 6 and 7 > 2'` renders as
    `'5 2'`. Twelve translators writing free prose into a rich-text key is
    exactly how that gets in, and nothing else in the suite would notice."""
    for text in (sd.usb_certificate_notice_line(),
                 sd.usb_certificate_details_text()):
        for tag in ("b", "i"):
            assert text.count(f"<{tag}>") == text.count(f"</{tag}>"), tag
        # no tag but the four this text is allowed to use
        assert not set(re.findall(r"<\s*/?\s*([a-zA-Z]+)", text)) - {
            "b", "i", "br"}


@pytest.mark.parametrize("code", ALL_CODES)
def test_every_language_has_the_disclosure_and_it_is_not_english(code):
    """A missing key falls back to English silently — which for THIS text means
    a German user is shown an English page about their own root certificate
    store. `test_i18n.py` catches the missing key; this catches the identity
    mapping that satisfies it without translating anything."""
    import json
    from pathlib import Path

    root = Path(sd.__file__).resolve().parent.parent.parent / "data" / "i18n"
    cat = json.loads(root.joinpath(f"{code}.json").read_text(encoding="utf-8"))
    keys = _english_keys()
    assert keys, "the sweep found no keys — it would pass for ever"
    for key in keys:
        assert key in cat, f"[{code}] missing: {key[:60]}…"
        if code == "zh_CN":
            # Chinese keeps the HTML and the two proper nouns and little else;
            # equality would be the only signal that matters and it is checked.
            pass
        assert cat[key] != key, (
            f"[{code}] left as English: {key[:60]}…")


def _english_keys() -> "list[str]":
    """The English source strings this feature adds, read out of the source.

    Selecting them by `inspect.getsource` rather than listing them by hand is
    what keeps the sweep from going blind when a sixth paragraph is added: a new
    `tr()` in these functions joins the sweep without anybody remembering to.
    """
    import inspect

    src = (inspect.getsource(sd.usb_certificate_notice_line)
           + inspect.getsource(sd.usb_certificate_details_text)
           + inspect.getsource(sd._label_what_this_changes))
    # Reconstruct each tr("…" "…") argument: implicitly concatenated literals.
    out = []
    for call in re.finditer(r'tr\(\s*((?:"(?:[^"\\]|\\.)*"\s*)+)\)', src,
                            re.S):
        parts = re.findall(r'"((?:[^"\\]|\\.)*)"', call.group(1))
        out.append("".join(parts).replace('\\"', '"').replace("\\\\", "\\"))
    return out


def test_the_notice_title_is_a_key_too():
    """The window's TITLE is user-facing and is the one string a `tr()` sweep
    over the text functions cannot see — it is written at the call site in
    `_show_usb_installer`."""
    import inspect
    import json
    from pathlib import Path

    src = inspect.getsource(sd.SettingsDialog._show_usb_installer)
    title = "What installing the driver changes"
    assert f'tr("{title}")' in src
    root = Path(sd.__file__).resolve().parent.parent.parent / "data" / "i18n"
    for code in ALL_CODES:
        cat = json.loads(root.joinpath(f"{code}.json").read_text(
            encoding="utf-8"))
        assert title in cat, f"[{code}] the notice title is not a key"
        assert cat[title] != title, f"[{code}] the notice title is English"

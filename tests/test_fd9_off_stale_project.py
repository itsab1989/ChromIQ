"""AN FD-9 PROJECT OPENED WITH FD-9 SUPPORT OFF IS LEFT AS IT WAS (review r2).

A user makes an FD-9 chart with Preferences > Beta on, then turns the Beta
off again and opens the same project. Two things must hold, and this file
proves both on the REAL main window, each half in its own process because the
switch is read once per process (restart-to-apply):

* S1: the project's ``meta.json`` is byte-identical afterwards. Leaving a tab
  writes the target's Create Chart settings, and with the Beta off the tab
  cannot show the FD-9, so it used to file the i1Pro it fell back to over the
  FD-9's own instrument, margins and gap.
* S2: no FD-9 layout code runs and no FD-9 module other than the switch is
  loaded. 4.3.21 knew no FD-9: such a chart is a chart for an instrument it
  does not know, and that is how the off app treats it.

The chart is generated by the app itself (Guided, Generate Chart) with real
ArgyllCMS, the way a user makes one.
"""

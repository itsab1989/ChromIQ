def _run(mode, settings, out):
    env = dict(os.environ)
    env.update(CHROMIQ_ROOT=str(ROOT), QT_QPA_PLATFORM="offscreen",
               CHROMIQ_SETTINGS_FILE=str(settings),
               CHROMIQ_PROBE_OUT=str(out), CHROMIQ_PROBE_MODE=mode)
    try:
        r = subprocess.run([sys.executable, "-c", PROBE], capture_output=True,
                           text=True, encoding="utf-8", errors="replace",
                           env=env, cwd=str(settings.parent), timeout=600)
    except subprocess.TimeoutExpired:
        pytest.fail(f"the {mode} probe did not finish in 600 s (a loaded "
                    "machine, or a window waiting for an answer)")
    line = next((ln for ln in r.stdout.splitlines() if ln.startswith("PROBE")),
                None)
    assert line, f"{mode} probe failed (exit {r.returncode}):\n{r.stderr[-3000:]}"
    return json.loads(line[len("PROBE"):])


def _flat_diff(was, now, path=""):
    """Only the leaves that differ, as {"a.b.c": (was, now)}."""
    if isinstance(was, dict) and isinstance(now, dict):
        out = {}
        for k in sorted(set(was) | set(now), key=str):
            out.update(_flat_diff(was.get(k), now.get(k), f"{path}.{k}"))
        return out
    return {} if was == now else {path.lstrip("."): (was, now)}


def _digest(project):
    return {p.relative_to(project).as_posix():
            hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(project.rglob("meta.json"))}


NAME = "I1iO-Stale-Project"
needs_argyll = pytest.mark.skipif(
    not (ARGYLL / "targen").exists(),
    reason="ArgyllCMS is needed to generate the i1iO chart")


@pytest.fixture(scope="module")
def i1io_project(tmp_path_factory):
    """One i1iO project, made by the app with the Beta on (Guided, Generate
    Chart, real ArgyllCMS). Each test works on its own copy."""
    base = tmp_path_factory.mktemp("i1io-made-on")
    out = base / "projects"
    on = _run("on", base / "on.ini", out)
    project = out / NAME
    metas = sorted(project.rglob("runs/*/meta.json"))
    assert metas, f"the i1iO chart was not generated: {on}"
    meta = json.loads(metas[0].read_text(encoding="utf-8"))
    ui = meta.get("create_chart_ui") or {}
    assert ui["guided"]["instrument"] == "IO2", (
        f"the generated chart is not an i1iO one, so this proves nothing: {on}")
    ti2 = next((project / "runs" / "run1").glob("*.ti2"))
    assert b'TARGET_INSTRUMENT "X-Rite i1iO"' in ti2.read_bytes()
    assert list((project / "runs" / "run1").glob("*.i1io.json"))
    yield project
    shutil.rmtree(base, ignore_errors=True)


def _copy_of(i1io_project, tmp_path):
    out = tmp_path / "projects"
    shutil.copytree(i1io_project, out / NAME)
    return out, out / NAME


def _run1_meta(project):
    return json.loads((project / "runs" / "run1" / "meta.json")
                      .read_text(encoding="utf-8"))


def _names_i1io_anywhere(meta):
    cs = meta.get("create_chart_settings") or {}
    ui = meta.get("create_chart_ui") or {}
    return sorted(
        [k for k in ("printtarg-i",) if (cs.get(k) or {}).get("value") == "IO2"]
        + [f"{b}.instrument" for b in ("guided", "engine_recipe")
           if (ui.get(b) or {}).get("instrument") == "IO2"])


@needs_argyll
def test_an_i1io_project_opened_with_the_beta_off_is_left_as_it_was(
        i1io_project, tmp_path):
    out, project = _copy_of(i1io_project, tmp_path)
    as_generated = _digest(project)
    # Keep what the user generated, to compare by eye when this goes red.
    keep = {k: (project / k).read_bytes() for k in as_generated}

    off = _run("off", tmp_path / "off.ini", out)
    after = _digest(project)
    changed = sorted(k for k in as_generated if as_generated[k] != after.get(k))
    if changed:
        k = changed[0]
        was = json.loads(keep[k])
        now = json.loads((project / k).read_text(encoding="utf-8"))
        diff = _flat_diff(was, now)
        if not diff:     # the same values, written again: show the bytes
            import difflib
            diff = "".join(difflib.unified_diff(
                keep[k].decode("utf-8").splitlines(True),
                (project / k).read_text(encoding="utf-8").splitlines(True),
                n=1))
        pytest.fail(f"opening the i1iO project with the Beta off rewrote "
                    f"{changed}; first difference in {k}: "
                    f"{json.dumps(diff)[:3000] if isinstance(diff, dict) else diff[:3000]}")
    assert off["instrument"] != "IO2"
    extra = sorted(set(off["loaded"]) - {"workflow.i1io", "workflow.i1io.support"})
    assert not extra, (
        "with i1iO support off, opening an i1iO project loaded i1iO code: "
        f"{extra}")
    shutil.rmtree(out, ignore_errors=True)


@needs_argyll
def test_a_change_the_user_makes_with_the_beta_off_is_kept(
        i1io_project, tmp_path):
    """With the Beta off, the user picks Letter and 2 pages on the i1iO run:
    that is the user's choice and is written (the FD-9's review r3 R3-1)."""
    out, project = _copy_of(i1io_project, tmp_path)
    got = _run("off-edit", tmp_path / "off.ini", out)
    assert got["loaded"] == ["Letter", 2], (
        f"the screen did not keep the user's change: {got}")
    meta = _run1_meta(project)
    guided = meta["create_chart_ui"]["guided"]
    # Guided keeps its own sheet and pages; the printtarg rows follow at
    # Generate, exactly as on an i1Pro run (review r3 control drive).
    assert (guided["paper"], guided["pages"]) == ("Letter", 2), (
        f"the paper and pages the user picked were not saved: {guided}")


@needs_argyll
def test_generating_an_i1pro_chart_into_the_i1io_run_leaves_no_i1io(
        i1io_project, tmp_path):
    """Generate Chart with the Beta off makes an i1Pro chart in run 1. Its
    meta.json must then describe that chart, not the i1iO."""
    out, project = _copy_of(i1io_project, tmp_path)
    got = _run("off-generate", tmp_path / "off.ini", out)
    ti2 = next((project / "runs" / "run1").glob("*.ti2"))
    head = ti2.read_bytes().split(b"BEGIN_DATA_FORMAT", 1)[0]
    assert b"i1iO" not in head, (
        f"the generate did not make an i1Pro chart, so this proves nothing: "
        f"{got}")
    meta = _run1_meta(project)
    assert not _names_i1io_anywhere(meta), (
        "run 1 holds an i1Pro chart but its meta.json still names the i1iO: "
        f"{_names_i1io_anywhere(meta)}")


@needs_argyll
def test_a_change_back_after_a_write_without_a_reload_is_kept(
        i1io_project, tmp_path):
    """The sheet as opened, Letter, the Profile-run pulldown writes (no
    reload), the first sheet again, leave the tab: the sheet picked last is
    filed, and the untouched i1iO instrument is carried (the FD-9's R4-1)."""
    out, project = _copy_of(i1io_project, tmp_path)
    got = _run("off-flip-pulldown", tmp_path / "off.ini", out)
    assert got["loaded"][0] == got["loaded"][1] and got["loaded"][0] != "Letter", (
        f"the screen did not come back to the sheet it opened on: {got}")
    assert "after the pulldown write: Letter" in got["windows"], (
        f"the pulldown write did not file the user's Letter: {got}")
    guided = _run1_meta(project)["create_chart_ui"]["guided"]
    assert guided["paper"] == got["loaded"][0], (
        f"the user's sheet was replaced by their own earlier Letter: {guided}")
    assert guided["instrument"] == "IO2", (
        f"the untouched i1iO instrument was not carried: {guided}")

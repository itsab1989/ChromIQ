def test_every_snapshot_of_a_bound_set_is_taken_after_the_sync():
    """THE SOURCE: each assignment of a bound set's targen snapshot is
    preceded by the sync, within a few lines. A new bind path that forgets it
    turns this red."""
    import re
    src = (ROOT / "ui" / "tabs" / "tab_chart.py").read_text(encoding="utf-8")
    lines = src.splitlines()
    snaps = [i for i, ln in enumerate(lines) if re.search(
        r"_(tc918|knut|prebuilt|preset_ti1)_targen_sig = (\(|self\._targen_signature)",
        ln)]
    assert len(snaps) >= 6, snaps
    for i in snaps:
        window = "\n".join(lines[max(0, i - 12):i + 1])
        assert "_sync_device_type_to_bound_set" in window or "_sync(" in window, (
            f"tab_chart.py:{i + 1} snapshots a bound patch set without "
            "first setting Device Type from it")



def _cal(path: Path, rep: str = "CMYK") -> Path:
    ch = {"CMYK": "CMYK_C CMYK_M CMYK_Y CMYK_K",
          "RGB": "RGB_R RGB_G RGB_B"}[rep]
    n = len(ch.split())
    path.write_text(
        'CAL\n\nDESCRIPTOR "Argyll Device Calibration State"\n'
        'ORIGINATOR "Argyll printcal"\nDEVICE_CLASS "OUTPUT"\n'
        f'COLOR_REP "{rep}"\n\nNUMBER_OF_FIELDS {n + 1}\n'
        f"BEGIN_DATA_FORMAT\n{rep}_I {ch}\nEND_DATA_FORMAT\n\n"
        "NUMBER_OF_SETS 2\nBEGIN_DATA\n"
        f"0 {' '.join(['0'] * n)}\n1 {' '.join(['1'] * n)}\nEND_DATA\n",
        encoding="utf-8")
    return path


def _capture_info(monkeypatch) -> list:
    shown: list = []
    from ui import tooltip_button as W
    from ui.tabs import tab_chart as TC

    def fake_exec(self):
        shown.append((self.windowTitle(), getattr(self, "_body_text", "")))
        return 0
    real_init = W.InfoDialog.__init__

    def init(self, title, body, *a, **k):
        real_init(self, title, body, *a, **k)
        self._body_text = body
    monkeypatch.setattr(W.InfoDialog, "__init__", init)
    monkeypatch.setattr(W.InfoDialog, "exec", fake_exec)
    assert TC.InfoDialog is W.InfoDialog
    return shown



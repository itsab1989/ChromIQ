"""Create Chart's "Device Type" says what the bound patch set IS (beta 7).

THE REPORT (forum, ajaytanna, 2026-10-03, CMYK + CR30 + PrintFab). He picked a
CR30 preset, ticked "Edit patch recipe (override preset)", chose CMYK and a
CMYK printer calibration, and Generate answered "The chart could not be built
... set Device Type to CMYK" with Device Type already reading CMYK.

The CR30 presets, like every built-in, carry their own RGB patch set. Picking
one never touched -d, so a CMYK left on the panel stayed there beside 450 RGB
patches; the "has the recipe changed?" snapshot was taken WITH that CMYK in it,
so his Generate saw nothing changed, laid the RGB set out again, and the CMYK
calibration refused it. A run built that way stored -d 4 beside its RGB .ti1,
which set the same trap every time the run was selected again.

So every place a patch set is bound sets -d from the set's COLOR_REP, through
one helper (`TabChart._sync_device_type_to_bound_set`), right before the
snapshot, and clears the -D add/remove-colorant rows. The table it reads is
GENERATED by running targen -d0..15 (`scripts/make_targen_device_types.py`),
and the first test here runs targen again so the table cannot drift.

And when the calibration really does not fit the patch set, the refusal comes
before anything is built and names the box that is the way out
(M-PATCHSET-CAL-INKS).
"""
